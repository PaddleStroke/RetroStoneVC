def main():
    rows = []
    for code in range(32, 128):
        ch = chr(code)
        if 'a' <= ch <= 'z':
            ch = ch.upper()
        g = G[ch]
        assert len(g) == 7 and all(len(r) == 5 for r in g), repr(ch)
        b = []
        for r in g + ["     "]:
            v = 0
            for i, c in enumerate(r):
                if c == '#':
                    v |= 0x80 >> (i + 1)  # columns 1..5 of the 8x8 cell
            b.append(v)
        rows.append((code, b))
    print("/* Generated by sdk/tools/gen_font.py: the RetroStone VC 5x7 font.")
    print(" * MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft). */")
    print("#include <stdint.h>\n")
    print("/* ASCII 32..127, 8 rows per glyph, bit 7 = leftmost pixel. */")
    print("const uint8_t rs_font_5x7[96][8] = {")
    for code, b in rows:
        name = chr(code) if 32 < code < 127 and chr(code) not in "\\*/" else "%d" % code
        print("    {%s}, /* %s */" % (", ".join("0x%02x" % v for v in b), name))
    print("};")


if __name__ == "__main__":
    main()
