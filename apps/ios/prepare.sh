#!/bin/sh
# The iOS apps, step 1 of 2: everything that is made on Linux (WSL, or the CI's ubuntu job) before a Mac builds the
# app (apps/ios/build.sh). Run from anywhere:
#
#   apps/ios/prepare.sh board [--preview]     RetroStone Board: build/ios/board/
#   apps/ios/prepare.sh arcade [--preview]    RetroStone Arcade: build/ios/arcade/ and build/bundle/gen-ios/ (the
#                                             generated sources of apps/launcher/bundle.mk, the iOS .conf: app.conf;
#                                             the modules to build: games.txt)
#
# It writes into build/ios/<app>/:
#   edition.conf          the app's edition (apps/ios/<app>/app.conf with the free set of its Android free edition)
#   gen/*.c               the generated C the Xcode project compiles: the texts and their fonts (gen_text.py), the
#                         pictures (gen_art.py), the edition (gen_edition.py): the same tools as the other builds
#   Assets.xcassets       the app icon (apps/ios/common/make_icon.py, from the Android icon's artwork)
#   app.env               the identity build.sh reads: NAME, BUNDLE_ID, IAP_PRODUCT, VERSION, BUILD
#   preview/*.png         --preview: the desktop build's pictures of the iOS unlock panel (a stand-in for StoreKit,
#                         apps/ios/tools/iap_preview.c), to look at without a Mac
# Needs: make, gcc, python3 with Pillow, numpy and fontTools, the fonts-noto-cjk and fonts-dejavu-core packages,
# SDL2's development files (the icon's pictures are drawn by the app's own code: sdl2-config).
# MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft).
set -eu

HERE=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
APP=${1:-}
PREVIEW=0
[ "${2:-}" = --preview ] && PREVIEW=1
case "$APP" in
board|arcade) ;;
*) echo "usage: $0 board|arcade [--preview]" >&2; exit 2 ;;
esac
cd "$REPO"
C=apps/ios/$APP/app.conf
OUT=build/ios/$APP
conf() { sed -n "s/^$1=//p" "$2"; }
say() { printf '\n== %s\n' "$*"; }
mkdir -p "$OUT/gen"

if [ "$APP" = board ]; then
    FREE=$(conf FREE_FROM "$C")
    VER=$(conf VERSION_FROM "$C")
    ICON=$(conf ICON_FROM "$C")
    say "RetroStone Board: the edition ($C, the free set of $FREE)"
    {
        echo "# generated by apps/ios/prepare.sh from $C and $FREE: do not edit"
        echo "APP_NAME=$(conf APP_NAME "$C")"
        echo "EXE_NAME=$(conf EXE_NAME "$C")"
        echo "FREE_GAMES=$(conf FREE_GAMES "$FREE")"
        echo "FREE_LEVELS=$(conf FREE_LEVELS "$FREE")"
        echo "IAP_PRODUCT=$(conf IAP_PRODUCT "$C")"
    } > "$OUT/edition.conf"
    cat "$OUT/edition.conf"
    say "the generated sources (texts, fonts, pictures, edition)"
    N=$OUT/native
    make --no-print-directory -f apps/boardgames/Makefile CONF="$OUT/edition.conf" B="$N" \
        "$N/gen/text_data.c" "$N/gen/art_data.c" "$N/gen/edition.c"
    cp "$N/gen/text_data.c" "$N/gen/art_data.c" "$N/gen/edition.c" "$OUT/gen/"
    say "the icon (the artwork of $ICON)"
    make --no-print-directory -f apps/boardgames/Makefile icon-art CONF="$ICON" B="$OUT/icon-build" \
        ICON_DIR="$OUT/icon-art" > "$OUT/icon-art.log" 2>&1 || { tail -20 "$OUT/icon-art.log"; exit 1; }
    python3 apps/ios/common/make_icon.py --conf "$ICON" --art "$OUT/icon-art" --out "$OUT/Assets.xcassets"
    VERSION=$(conf APP_VERSION_NAME "$VER")
    BUILD=$(conf APP_VERSION_CODE "$VER")
    if [ "$PREVIEW" = 1 ]; then
        say "the unlock panel in pictures (the desktop build, apps/ios/tools/iap_preview.c)"
        P=$OUT/preview-build
        make --no-print-directory -s -f apps/boardgames/Makefile host CONF="$OUT/edition.conf" B="$P" \
            IAP_SRC=apps/ios/tools/iap_preview.c
        X=$P/host/retrostoneboard
        mkdir -p "$OUT/preview"
        # the strategy tab, its first locked game tapped (the playable ones come first: the 4th card, Lasca); then the
        # same in other languages, landscape, before the price is known, while the store works, and once bought
        $X --shot "$OUT/preview/menu.bmp" --tab 1
        $X --shot "$OUT/preview/panel.bmp" --tab 1 --taps "0.25,0.45"
        for l in fr ja el de; do $X --shot "$OUT/preview/panel-$l.bmp" --tab 1 --taps "0.25,0.45" --lang $l; done
        $X --shot "$OUT/preview/panel-wide.bmp" --size 1280x720 --tab 1 --taps "0.69,0.45"
        IAP_PREVIEW_PRICE='' $X --shot "$OUT/preview/panel-noprice.bmp" --tab 1 --taps "0.25,0.45"
        IAP_PREVIEW_BUSY=1 $X --shot "$OUT/preview/panel-busy.bmp" --tab 1 --taps "0.25,0.45"
        IAP_PREVIEW_UNLOCKED=1 $X --shot "$OUT/preview/menu-unlocked.bmp" --tab 1
        python3 -c "import glob; from PIL import Image; [Image.open(f).save(f[:-3] + 'png') for f in glob.glob('$OUT/preview/*.bmp')]"
        rm -f "$OUT/preview/"*.bmp
        ls "$OUT/preview"
    fi
fi

if [ "$APP" = arcade ]; then
    FREE=$(conf FREE_FROM "$C")
    VER=$(conf VERSION_FROM "$C")
    ICON=$(conf ICON_FROM "$C")
    VERSION=$(conf APP_VERSION_NAME "$VER")
    BUILD=$(conf APP_VERSION_CODE "$VER")
    say "RetroStone Arcade: the app's .conf ($C, the free set of $FREE)"
    {
        echo "# generated by apps/ios/prepare.sh from $C and $FREE: do not edit"
        echo "PROFILE=ios"
        echo "APP_NAME=$(conf APP_NAME "$C")"
        echo "APP_ID=$(conf BUNDLE_ID "$C")"
        echo "APP_VERSION_NAME=$VERSION"
        echo "APP_VERSION_CODE=$BUILD"
        echo "EXE_NAME=$(conf EXE_NAME "$C")"
        echo "FREE_GAMES=$(conf FREE_GAMES "$FREE")"
        echo "HIDDEN_GAMES=$(conf HIDDEN_GAMES "$FREE")"
        echo "IAP_PRODUCT=$(conf IAP_PRODUCT "$C")"
        echo "PAID_APP_NAME=$(conf APP_NAME "$C")"
    } > "$OUT/app.conf"
    cat "$OUT/app.conf"
    say "the generated sources (the games' assets and texts, the launcher's texts, the credits, the catalogue)"
    B="make --no-print-directory -f apps/launcher/bundle.mk CONF=$OUT/app.conf"
    $B gen
    $B build/bundle/gen-ios/catalog.c
    python3 apps/launcher/tools/gen_catalog.py --conf "$OUT/app.conf" --list > "$OUT/games.txt"
    echo "games: $(cat "$OUT/games.txt")"
    say "the icon (the artwork of $ICON)"
    python3 apps/ios/common/make_icon.py --conf "$ICON" --out "$OUT/Assets.xcassets"
    if [ "$PREVIEW" = 1 ]; then
        say "the unlock panel in pictures (the desktop build, apps/ios/tools/iap_preview.c)"
        $B SKIP_ASSETS=1 IAP_SRC=apps/ios/tools/iap_preview.c > "$OUT/preview-build.log" 2>&1 \
            || { tail -30 "$OUT/preview-build.log"; exit 1; }
        X=build/bundle/host-ios/retrostonearcade_headless
        T=$OUT/preview-saves
        mkdir -p "$OUT/preview" "$T"
        printf '10 tap-at 56 156\n' > "$T/panel.txt"
        $X --saves "$T" --width 427 --frames 40 --shot 39:"$OUT/preview/menu.png" > /dev/null
        $X --saves "$T" --width 427 --frames 60 --input "$T/panel.txt" --shot 59:"$OUT/preview/panel.png" > /dev/null
        for l in fr ja de; do
            $X --saves "$T" --lang $l --width 427 --frames 60 --input "$T/panel.txt" \
                --shot 59:"$OUT/preview/panel-$l.png" > /dev/null
        done
        IAP_PREVIEW_PRICE='' $X --saves "$T" --frames 60 --input "$T/panel.txt" \
            --shot 59:"$OUT/preview/panel-noprice-320.png" > /dev/null
        IAP_PREVIEW_UNLOCKED=1 $X --saves "$T" --width 427 --frames 40 --shot 39:"$OUT/preview/menu-unlocked.png" \
            > /dev/null
        ls "$OUT/preview"
    fi
fi

{
    echo "NAME=$(conf APP_NAME "$C")"
    echo "TARGET=$(conf EXE_NAME "$C")"
    echo "BUNDLE_ID=$(conf BUNDLE_ID "$C")"
    echo "IAP_PRODUCT=$(conf IAP_PRODUCT "$C")"
    echo "VERSION=$VERSION"
    echo "BUILD=$BUILD"
} > "$OUT/app.env"
say "$OUT/app.env"
cat "$OUT/app.env"
