#!/bin/bash
# Installs the Android build toolchain for the RetroStone Arcade apps, in ONE folder of its own
# (default ~/android-app-sdk; never inside a LineageOS tree, never in the system PATH or ~/.bashrc).
# Idempotent: run it again at any time, it only adds what is missing.
#
#   apps/android/setup-toolchain.sh              the toolchain
#   apps/android/setup-toolchain.sh --emulator   also the emulator and an x86_64 system image (smoke tests, ~2 GB)
#
# What it installs (the versions are pinned below):
#   OpenJDK 17 (apt, openjdk-17-jdk-headless; the system's default java is left alone)
#   ~/android-app-sdk/sdk          ANDROID_HOME: cmdline-tools, platform-tools, the platform, build-tools, the NDK
#   ~/android-app-sdk/gradle-home  GRADLE_USER_HOME: the Gradle distribution of apps/android/gradlew, its caches
#   ~/android-app-sdk/env.sh       the environment (sourced by apps/android/build.sh)
# It accepts the Android SDK licences with sdkmanager --licenses.
#
# MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft).
set -euo pipefail

ROOT=${ANDROID_APP_SDK:-$HOME/android-app-sdk}
CMDLINE_TOOLS_ZIP=commandlinetools-linux-16111833_latest.zip      # cmdline-tools 23.0
PLATFORM="platforms;android-36"                                    # compileSdk / targetSdk 36 (Android 16)
BUILD_TOOLS="build-tools;36.1.0"
NDK_VERSION=27.3.13750724                                          # NDK r27d (LTS)
EMU_IMAGE="system-images;android-30;default;x86_64"                # --emulator only
HERE=$(cd "$(dirname "$0")" && pwd)

WITH_EMU=0
[ "${1:-}" = "--emulator" ] && WITH_EMU=1

# Buildroot-style hosts put spaces in PATH (WSL appends the Windows PATH): use a clean one
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin

say() { printf '\n== %s\n' "$*"; }

# ---- OpenJDK 17 (apt) ---------------------------------------------------------------------------------------
JAVA_HOME=/usr/lib/jvm/java-17-openjdk-amd64
if [ ! -x "$JAVA_HOME/bin/javac" ]; then
    say "OpenJDK 17 (apt)"
    SUDO=""; [ "$(id -u)" -ne 0 ] && SUDO=sudo
    $SUDO apt-get update -qq
    $SUDO apt-get install -y -qq openjdk-17-jdk-headless unzip curl
fi
export JAVA_HOME

mkdir -p "$ROOT/sdk" "$ROOT/gradle-home" "$ROOT/downloads"
export ANDROID_HOME="$ROOT/sdk" ANDROID_SDK_ROOT="$ROOT/sdk" GRADLE_USER_HOME="$ROOT/gradle-home"
# the AVDs (--emulator) live here too, not in ~/.android
export ANDROID_AVD_HOME="$ROOT/avd" ANDROID_USER_HOME="$ROOT/android-user"

# ---- command-line tools -------------------------------------------------------------------------------------
SDKM="$ANDROID_HOME/cmdline-tools/latest/bin/sdkmanager"
if [ ! -x "$SDKM" ]; then
    say "Android command-line tools"
    Z="$ROOT/downloads/$CMDLINE_TOOLS_ZIP"
    [ -f "$Z" ] || curl -fSL -o "$Z.part" "https://dl.google.com/android/repository/$CMDLINE_TOOLS_ZIP"
    [ -f "$Z.part" ] && mv "$Z.part" "$Z"
    rm -rf "$ROOT/downloads/cmdline-tools" "$ANDROID_HOME/cmdline-tools/latest"
    unzip -q "$Z" -d "$ROOT/downloads"
    mkdir -p "$ANDROID_HOME/cmdline-tools"
    mv "$ROOT/downloads/cmdline-tools" "$ANDROID_HOME/cmdline-tools/latest"
fi

# ---- licences and packages ----------------------------------------------------------------------------------
say "SDK licences"
yes | "$SDKM" --licenses > /dev/null 2>&1 || true
PKGS=(platform-tools "$PLATFORM" "$BUILD_TOOLS" "ndk;$NDK_VERSION")
[ "$WITH_EMU" = 1 ] && PKGS+=(emulator "$EMU_IMAGE")
MISSING=()
for p in "${PKGS[@]}"; do
    d="$ANDROID_HOME/$(echo "$p" | tr ';' '/')"
    [ -e "$d/package.xml" ] || [ -e "$d/source.properties" ] || MISSING+=("$p")
done
if [ ${#MISSING[@]} -gt 0 ]; then
    say "sdkmanager: ${MISSING[*]}"
    # (not "yes | sdkmanager" under pipefail: yes ends with SIGPIPE, which would fail the pipeline)
    set +o pipefail
    yes | "$SDKM" --install "${MISSING[@]}" > "$ROOT/downloads/sdkmanager.log" 2>&1
    rc=${PIPESTATUS[1]}
    set -o pipefail
    [ "$rc" = 0 ] || { tail -c 2000 "$ROOT/downloads/sdkmanager.log"; exit 1; }
fi

# ---- the environment file -----------------------------------------------------------------------------------
cat > "$ROOT/env.sh" <<ENV
# generated by apps/android/setup-toolchain.sh: source it to build the Android apps
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
export JAVA_HOME=$JAVA_HOME
export ANDROID_HOME=$ANDROID_HOME
export ANDROID_SDK_ROOT=$ANDROID_HOME
export ANDROID_NDK_HOME=$ANDROID_HOME/ndk/$NDK_VERSION
export GRADLE_USER_HOME=$GRADLE_USER_HOME
export ANDROID_AVD_HOME=$ANDROID_AVD_HOME
export ANDROID_USER_HOME=$ANDROID_USER_HOME
export PATH=\$JAVA_HOME/bin:\$ANDROID_HOME/cmdline-tools/latest/bin:\$ANDROID_HOME/platform-tools:\$ANDROID_HOME/build-tools/${BUILD_TOOLS#build-tools;}:\$ANDROID_HOME/emulator:\$PATH
ENV

# ---- the Gradle wrapper (apps/android/gradlew downloads its Gradle into GRADLE_USER_HOME once) ------------
say "Gradle (through the wrapper)"
( cd "$HERE" && ./gradlew --version --quiet > /dev/null ) && echo "gradle ok"

# ---- an emulator for smoke tests (--emulator) -----------------------------------------------------------------
if [ "$WITH_EMU" = 1 ] && [ ! -d "$ANDROID_AVD_HOME/rsvc_smoke.avd" ]; then
    say "AVD rsvc_smoke ($EMU_IMAGE)"
    mkdir -p "$ANDROID_AVD_HOME"
    echo no | "$ANDROID_HOME/cmdline-tools/latest/bin/avdmanager" create avd -n rsvc_smoke -k "$EMU_IMAGE" -d pixel_4 --force > /dev/null
fi

say "Done"
echo "JDK:            $("$JAVA_HOME/bin/java" -version 2>&1 | head -1)"
echo "ANDROID_HOME:   $ANDROID_HOME"
echo "NDK:            $ANDROID_HOME/ndk/$NDK_VERSION"
echo "platform:       $PLATFORM, $BUILD_TOOLS"
echo "env:            $ROOT/env.sh"
du -sh "$ROOT" 2>/dev/null | sed 's/^/disk:           /'
