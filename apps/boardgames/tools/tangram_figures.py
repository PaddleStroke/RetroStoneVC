def from_design(line, chapter, name=None):
    """a figure from a line of tangram_design.py's .txt: "name.i K rot flip ax bx ay by" seven times"""
    t = line.split()
    f = Fig(name or t[0], chapter)
    for i in range(1, len(t), 7):
        k, rot, flip, ax, bx, ay, by = t[i:i + 7]
        f.vat(k, int(rot), 0, (N(Fr(int(ax), 4), Fr(int(bx), 4)), N(Fr(int(ay), 4), Fr(int(by), 4))), int(flip))
    return f


def from_table(chapter, name, tans):
    f = Fig(name, chapter)
    for t in tans.split():
        k, rot, flip, ax, bx, ay, by = map(int, t.split(","))
        f.vat(KINDS[k], rot, 0, (N(Fr(ax, 4), Fr(bx, 4)), N(Fr(ay, 4), Fr(by, 4))), flip)
    return f


