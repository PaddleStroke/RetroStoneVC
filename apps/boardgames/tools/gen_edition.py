#!/usr/bin/env python3
"""The app's edition, read from its .conf at build time: build/<...>/gen/edition.c (src/edition.h).

    python3 apps/boardgames/tools/gen_edition.py --conf apps/android/app-boardfree.conf --out build/boardgames/gen

RetroStone Board (apps/android/app-board.conf, the default: every game, every level) or RetroStone Board Free
(apps/android/app-boardfree.conf): the keys APP_NAME, EXE_NAME, FREE_GAMES (the games playable besides the puzzles,
"all" or none: every game), FREE_LEVELS (the levels playable in each game of levels, 0 or none: all of them),
PAID_APP_NAME, PAID_APP_ID, PAID_STORE_URL (the paid app the "full version" panel opens), IAP_PRODUCT (the
in-app purchase that unlocks everything, apps/common/iap.h: the iOS app's product id; none: nothing sold in the
app); for the Settings page: APP_VERSION_NAME, APP_ID, REVIEW_URL (Leave a review; default: the app's Google Play
page), SUPPORT_URL (Leave a tip when no store sells tips; empty: no row), REPORT_URL (Report a problem; default
mailto:AppBugReport@8bcraft.com), SOURCE_URL (Star on GitHub), PRIVACY_URL (the policy's web page; empty: the in-app page
only), TIP_PRODUCTS (the store's three consumable tip products, ids between spaces; empty: none).
Plain KEY=value lines, '#' a comment line. A FREE_GAMES id that no game registers stops the build. The
file is written only when it changes, so the app is rebuilt only then.
MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft).
"""
import argparse
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)


def read_conf(path):
    conf = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                conf[k.strip()] = v.strip()
    return conf


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def default_review(conf):
    """the app's own store page (Leave a review), from its APP_ID; none without one"""
    app_id = conf.get("APP_ID", "")
    return "https://play.google.com/store/apps/details?id=" + app_id if app_id else ""


def game_ids():
    ids = set()
    for f in glob.glob(os.path.join(APP, "src", "games", "*.c")):
        with open(f, encoding="utf-8") as fh:
            ids.update(re.findall(r'\.id\s*=\s*"([a-z0-9_]+)"', fh.read()))
    return ids


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--conf", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    conf = read_conf(a.conf)
    free = conf.get("FREE_GAMES", "all").split()
    if free == ["all"]:
        free = []
    unknown = sorted(set(free) - game_ids())
    if unknown:
        sys.exit("%s: FREE_GAMES names no game: %s" % (a.conf, " ".join(unknown)))
    levels = conf.get("FREE_LEVELS", "0") or "0"
    if not levels.isdigit():
        sys.exit("%s: FREE_LEVELS is not a number: %s" % (a.conf, levels))
    paid_id = conf.get("PAID_APP_ID", "")
    if (free or int(levels)) and not paid_id and not conf.get("IAP_PRODUCT"):
        sys.exit("%s: a free edition needs PAID_APP_ID (the paid app its panel opens) or IAP_PRODUCT" % a.conf)
    text = "\n".join([
        "/* generated by apps/boardgames/tools/gen_edition.py from %s: do not edit */" % os.path.basename(a.conf),
        '#include "edition.h"',
        "const char ed_app_name[] = %s;" % c_string(conf.get("APP_NAME", "RetroStone Board")),
        "const char ed_exe_name[] = %s;" % c_string(conf.get("EXE_NAME", "RetroStoneBoard")),
        "const char ed_free_games[] = %s;" % c_string(" ".join(free)),
        "const int ed_free_levels = %d;" % int(levels),
        "const int ed_free = %d;" % (1 if free or int(levels) else 0),
        "const char ed_paid_name[] = %s;" % c_string(conf.get("PAID_APP_NAME", "")),
        "const char ed_paid_id[] = %s;" % c_string(paid_id),
        "const char ed_paid_url[] = %s;" % c_string(conf.get("PAID_STORE_URL", "")),
        "const char ed_iap_product[] = %s;" % c_string(conf.get("IAP_PRODUCT", "")),
        # the Settings page: the version, the links (an empty one hides its row), the tips sold in the app
        "const char ed_version[] = %s;" % c_string(conf.get("APP_VERSION_NAME", "")),
        "const char ed_app_id[] = %s;" % c_string(conf.get("APP_ID", "")),
        "const char ed_review_url[] = %s;" % c_string(conf.get("REVIEW_URL", default_review(conf))),
        "const char ed_support_url[] = %s;" % c_string(conf.get("SUPPORT_URL", "")),
        "const char ed_report_url[] = %s;" % c_string(conf.get("REPORT_URL", "mailto:AppBugReport@8bcraft.com")),
        "const char ed_source_url[] = %s;" % c_string(conf.get("SOURCE_URL",
                                                                "https://github.com/PaddleStroke/RetroStoneVC")),
        "const char ed_privacy_url[] = %s;" % c_string(conf.get("PRIVACY_URL", "")),
        "const char ed_tip_products[] = %s;" % c_string(" ".join(conf.get("TIP_PRODUCTS", "").split())),
        "",
    ])
    os.makedirs(a.out, exist_ok=True)
    out = os.path.join(a.out, "edition.c")
    try:
        with open(out, encoding="utf-8") as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
