#!/usr/bin/env python3
"""Cosmo Corgi asset build: the code-drawn sheets (make_art.py) -> tiles, palettes, maps and sprites; the music
(make_music.py) -> build/gen/cosmocorgi/assets.c + assets.h.

    build_assets.py --out build/gen/cosmocorgi [--art games/cosmocorgi/art] [--tileset IGNORED]

MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/cosmocorgi/LICENSE.
"""
import argparse
import glob
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "games", "common", "tools"))
import rsasset  # noqa: E402
import make_art  # noqa: E402

# BG palettes: 0 the UI (the kit), 1-3 the walls (rock, station, ice), 4 the big planet (a tall screen), 5 the logo
# (the kit), 6 the clouds, 7 the stars
PAL_WALLS, PAL_LOGO, PAL_CLOUDS, PAL_STARS = 1, 5, 6, 7
PAL_TALL = 4                                              # a tall screen: the big planet
# OBJ palettes: 0 the corgi (P1), 1 P2, 2 the robots and the bosses, 3 the kit, 4 P3, 5 P4, 6 the props, 7 the gold
# robots (the capsule groups; a boss flashes in it when hit)
OBJ_PAL = {"hero": 0, "robots": 2, "props": 6}
PAL_GOLD = 7
PLAYER_SLOTS = {1: 1, 2: 4, 3: 5}
# BG1 the UI (the kit: 0..767 with the glyph pool), BG2 the walls, BG3 the clouds, BG4 the stars
VR_BG1, VR_BG2, VR_BG3, VR_BG4, VR_OBJ = 0, 1024, 1280, 1792, 3072
KIT_OBJ_TILE = 512                                        # the kit's sprites (house_ui.h HU_OBJ_TILES) after ours
BOSS_TILES = 2 * 48                                       # one boss at a time: two 64x48 frames


def cells8(img, x0, y0, w, h):
    return [rsasset.cell(img, x0 + x * 8, y0 + y * 8, 8, 8) for y in range(h // 8) for x in range(w // 8)]


def arr(name, data):
    return "const uint16_t %s[%d] = {%s};" % (name, len(data), ", ".join("0x%04x" % v for v in data))


def remap(p16, mapping):
    """p16 (RGB555, entry 0 transparent) with the colours of mapping (RGB888 -> RGB888) replaced."""
    m = {rsasset.to555(a): rsasset.to555(b) for a, b in mapping.items()}
    return [m.get(v, v) if i else v for i, v in enumerate(p16)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "sprites.png")):
        make_art.write_all(a.art)
    c = ["/* Generated by games/cosmocorgi/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/cosmocorgi/tools/build_assets.py. Do not edit. */",
         "#ifndef GM_ASSETS_H\n#define GM_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n",
         "#define VR_BG1 %d\n#define VR_BG2 %d\n#define VR_BG3 %d\n#define VR_BG4 %d\n#define VR_OBJ %d\n"
         "#define KIT_OBJ_TILE %d" % (VR_BG1, VR_BG2, VR_BG3, VR_BG4, VR_OBJ, KIT_OBJ_TILE),
         "#define PAL_WALLS %d\n#define PAL_LOGO %d\n#define PAL_CLOUDS %d\n#define PAL_STARS %d\n#define PAL_GOLD %d\n"
         "#define PAL_TALL %d" % (PAL_WALLS, PAL_LOGO, PAL_CLOUDS, PAL_STARS, PAL_GOLD, PAL_TALL)]
    stats = []

    # ---- BG2: the walls, 8 tiles per theme, one palette each -------------------------------------------------------
    timg = rsasset.load(os.path.join(a.art, make_art.TERRAIN[0]))
    ttiles, tmap = [], []
    for t in range(3):
        cells = [rsasset.cell(timg, k * 8, t * 8, 8, 8) for k in range(len(make_art.TER_KINDS))]
        r = rsasset.convert_bg(cells, 1, pal_base=PAL_WALLS + t, tile_base=len(ttiles), reserve_blank=(t == 0))
        assert len(r.palettes) == 1
        ttiles += r.tiles
        tmap += [m[0] for m in r.metas]
        c.append(arr("gm_walls_pal%d" % t, rsasset.palette16(r.palettes[0])))
    c.append(rsasset.c_bytes("gm_walls_tiles", rsasset.tiles_bytes(ttiles)))
    c.append("const int gm_walls_tile_count = %d;" % len(ttiles))
    c.append(arr("gm_walls_map", tmap))
    h.append("enum { %s, TER_KINDS };" % ", ".join("TK_%s" % k.upper() for k in make_art.TER_KINDS))
    h.append("extern const uint8_t gm_walls_tiles[];\nextern const int gm_walls_tile_count;")
    h.append("extern const uint16_t gm_walls_map[3 * TER_KINDS];")
    h.append("extern const uint16_t gm_walls_pal0[16], gm_walls_pal1[16], gm_walls_pal2[16];")
    stats.append("walls %d" % len(ttiles))

    # ---- BG3: the clouds (one palette per section theme); BG4: the stars -----------------------------------------------
    for key, pal in (("clouds", PAL_CLOUDS), ("stars", PAL_STARS)):
        f, w, hh = make_art.PANORAMAS[key]
        img = rsasset.load(os.path.join(a.art, f))
        r = rsasset.convert_bg(cells8(img, 0, 0, w, hh), 1, pal_base=pal, tile_base=0)
        assert len(r.palettes) == 1, key
        up = key.upper()
        c.append(rsasset.c_bytes("gm_%s_tiles" % key, rsasset.tiles_bytes(r.tiles)))
        c.append("const int gm_%s_tile_count = %d;" % (key, len(r.tiles)))
        c.append(arr("gm_%s_map" % key, [m[0] for m in r.metas]))
        p16 = rsasset.palette16(r.palettes[0])
        h.append("#define %s_W %d\n#define %s_H %d" % (up, w // 8, up, hh // 8))
        h.append("extern const uint8_t gm_%s_tiles[];\nextern const int gm_%s_tile_count;" % (key, key))
        h.append("extern const uint16_t gm_%s_map[%s_W * %s_H];" % (key, up, up))
        if key == "clouds":
            pals = p16 + [v for t in (1, 2, 3) for v in remap(p16, make_art.CLOUD_THEMES[t])]
            c.append(arr("gm_clouds_pal", pals))
            h.append("extern const uint16_t gm_clouds_pal[4 * 16];")
            cloud_pal = r.palettes[0]
            # a tall screen: the clouds without their planets (the copies past the stage): the same palette, their own
            # tiles after the panorama's (loaded at VR_BG3 + gm_clouds_tile_count on a tall screen only)
            bare = rsasset.load(os.path.join(a.art, make_art.CLOUDS_BARE))
            rb = rsasset.convert_bg(cells8(img, 0, 0, w, hh) + cells8(bare, 0, 0, w, hh), 1, pal_base=pal, tile_base=0)
            assert rb.palettes == r.palettes and rb.tiles[:len(r.tiles)] == r.tiles
            extra = rb.tiles[len(r.tiles):]
            assert VR_BG3 + len(rb.tiles) <= VR_BG4, "the bare clouds' tiles overlap the stars'"
            c.append(rsasset.c_bytes("gm_clouds_extra_tiles", rsasset.tiles_bytes(extra)))
            c.append("const int gm_clouds_extra_count = %d;" % len(extra))
            c.append(arr("gm_clouds_bare_map", [m[0] for m in rb.metas[len(r.metas):]]))
            h.append("extern const uint8_t gm_clouds_extra_tiles[];\nextern const int gm_clouds_extra_count;")
            h.append("extern const uint16_t gm_clouds_bare_map[CLOUDS_W * CLOUDS_H];")
            stats.append("bare clouds %d" % len(extra))
        else:
            c.append(arr("gm_stars_pal", p16))
            h.append("extern const uint16_t gm_stars_pal[16];")
            for name, rgb in (("STAR_A", make_art.STARS[0]), ("STAR_B", make_art.STARS[1])):
                h.append("#define IDX_%s %d" % (name, r.palettes[0].index(rsasset.to555(rgb)) + 1))
        stats.append("%s %d" % (key, len(r.tiles)))

    # ---- a tall screen only: the nebula's cloud bank (BG2, in the clouds' palette) and the big planet (BG4) -----------
    for key, pal in (("bank", PAL_CLOUDS), ("planet", PAL_TALL)):
        f, w, hh = make_art.BANKS[key]
        img = rsasset.load(os.path.join(a.art, f))
        r = rsasset.convert_bg(cells8(img, 0, 0, w, hh), 1, pal_base=pal, tile_base=0)
        assert len(r.palettes) == 1, key
        assert key != "bank" or len(r.tiles) <= 224, "the bank's tiles: BG2 32..255 (draw.c VR_BANK; 256: the clouds)"
        if key == "bank":                                    # the clouds' palette indices (its colours are theirs)
            ix = [0] + [cloud_pal.index(v) + 1 for v in r.palettes[0]]
            r.tiles = [[ix[v] for v in t] for t in r.tiles]
        else:
            c.append(arr("gm_planet_pal", rsasset.palette16(r.palettes[0])))
            h.append("extern const uint16_t gm_planet_pal[16];")
        up = key.upper()
        c.append(rsasset.c_bytes("gm_%s_tiles" % key, rsasset.tiles_bytes(r.tiles)))
        c.append("const int gm_%s_tile_count = %d;" % (key, len(r.tiles)))
        c.append(arr("gm_%s_map" % key, [m[0] for m in r.metas]))
        h.append("#define %s_W %d\n#define %s_H %d" % (up, w // 8, up, hh // 8))
        h.append("extern const uint8_t gm_%s_tiles[];\nextern const int gm_%s_tile_count;" % (key, key))
        h.append("extern const uint16_t gm_%s_map[%s_W * %s_H];" % (key, up, up))
        stats.append("%s %d" % (key, len(r.tiles)))
    assert len(r.tiles) <= 1024 - 96, "the planet's tiles: BG4's 1024 from VR_BG4, after the stars (draw.c VR_PLANET)"

    # ---- sprites ----------------------------------------------------------------------------------------------------
    sheet = rsasset.load(os.path.join(a.art, "sprites.png"))
    bsheet = rsasset.load(os.path.join(a.art, "bosses.png"))
    tiles, rows, names, pals = [], [], [], [0] * 128
    boss_frames = [rsasset.cell(bsheet, x + i * 64, y, 64, 48) for _n, x, y in make_art.BOSSES for i in range(2)]
    boss_tiles = []
    idx = 0
    for g in ("hero", "robots", "props"):
        ents = [e for e in make_art.SPRITES if e[6] == g]
        frames = []
        for name, x, y, w, hh, n, _g in ents:
            frames += [rsasset.cell(sheet, x + i * w, y, w, hh) for i in range(n)]
        extra = boss_frames if g == "robots" else []
        cols = set()
        for fr in frames + extra:
            cols |= rsasset.colors_of(fr)
        assert len(cols) <= 15, (g, len(cols), sorted(rsasset.rgb888(v) for v in cols))
        ro = rsasset.convert_obj(frames + extra)
        p16 = rsasset.palette16(ro.palette)
        pals[OBJ_PAL[g] * 16:OBJ_PAL[g] * 16 + 16] = p16
        if g == "hero":                                      # players 2-4: the paint and the fur recoloured
            for p, slot in PLAYER_SLOTS.items():
                m = dict(zip(make_art.ACC, make_art.ACC_P[p]))
                m.update(zip(make_art.FUR, make_art.FUR_P[p]))
                pals[slot * 16:slot * 16 + 16] = remap(p16, m)
        if g == "robots":                                    # the gold groups
            pals[PAL_GOLD * 16:PAL_GOLD * 16 + 16] = remap(p16, make_art.GOLD)
            nrob = sum(fr_w * fr_h // 64 for _f, fr_w, fr_h in ro.frames[:len(frames)])
            boss_tiles = ro.tiles[nrob:]
            ro.tiles = ro.tiles[:nrob]
        k = 0
        for name, x, y, w, hh, n, _g in ents:
            names.append("SPR_%s = %d" % (name.upper(), idx))
            for f in range(n):
                first, fw, fh = ro.frames[k]
                rows.append("{%d, %d, %d, %d}" % (len(tiles) + first, fw, fh, OBJ_PAL[g]))
                k += 1
                idx += 1
        tiles += ro.tiles
    boss_slot = len(tiles)
    names.append("SPR_BOSS = %d" % idx)
    for f in range(2):
        rows.append("{%d, 64, 48, %d}" % (boss_slot + f * 48, OBJ_PAL["robots"]))
        idx += 1
    assert len(boss_tiles) == 4 * BOSS_TILES
    assert boss_slot + BOSS_TILES <= KIT_OBJ_TILE, "the sprites overlap the kit's tiles: raise KIT_OBJ_TILE"
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(names), idx))
    h.append("#define BOSS_SLOT %d\n#define BOSS_TILES %d" % (boss_slot, BOSS_TILES))
    h.append("typedef struct gm_sprite_def { uint16_t tile; uint8_t w, h, pal; } gm_sprite_def;")
    h.append("extern const gm_sprite_def gm_spr[SPR_COUNT];")
    h.append("extern const uint8_t gm_obj_tiles[];\nextern const int gm_obj_tile_count;\n"
             "extern const uint16_t gm_obj_pals[128];\nextern const uint8_t gm_boss_tiles[4 * BOSS_TILES * 32];")
    c.append("const gm_sprite_def gm_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("gm_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gm_obj_tile_count = %d;" % len(tiles))
    c.append(rsasset.c_bytes("gm_boss_tiles", rsasset.tiles_bytes(boss_tiles)))
    c.append(rsasset.c_u16("gm_obj_pals", pals))
    stats.append("OBJ %d + boss slot %d" % (len(tiles), BOSS_TILES))

    # ---- the asset pack: the music ------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        data = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, data, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(data)))
    c.append("const rs_asset_entry gm_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry gm_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: tiles %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
