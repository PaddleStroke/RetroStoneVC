#!/usr/bin/env python3
"""Gopher Dig asset build: the code-drawn sheets (make_art.py) -> tiles, palettes, cell tables and sprites; the music
(make_music.py) -> build/gen/gopherdig/assets.c + assets.h.

    build_assets.py --out build/gen/gopherdig [--art games/gopherdig/art] [--tileset IGNORED]

The well's tiles are one bank shared by BG2 (the falling blocks), BG3 (the shaking ones) and BG4 (the well, the earth
around it, the sky's clouds): the blocks in BG palettes 1 and 2, the stratum tiles in palette indices (BG 3: each
stratum's palette, swapped line by line by draw.c's raster), the buried things in BG 6 (the same), the surface in BG 7.

MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/gopherdig/LICENSE.
"""
import argparse
import glob
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "games", "common", "tools"))
import rsasset  # noqa: E402
import house_style as hs  # noqa: E402
import make_art  # noqa: E402

PAL_BLOCK_A, PAL_BLOCK_B, PAL_STRATUM, PAL_LOGO, PAL_DECOR, PAL_SURFACE = 1, 2, 3, 5, 6, 7
OBJ_PAL = {"hero": 0, "hero2": 1, "props": 2, "crumbs": 6}  # OBJ 3: the house kit sprites; OBJ 4, 5: players 3, 4
VR_BG1, VR_WELL, VR_OBJ = 0, 1024, 3072
BAR_TILE = 768                                            # the air gauge's tiles on BG1 (after the kit's glyph pool)
KIT_OBJ_TILE = 512                                        # the kit's sprites (house_ui.h HU_OBJ_TILES) after ours
# players 2-4: the hard hat's hue rotated (house_style.player_palettes): yellow -> blue for P2, then the two hues
# farthest from those; the fur, the cream, the nose and the lamp never change
P2_HUE = (0.10, 0.20, 0.45)


def arr(name, data, static=False):
    return "%sconst uint16_t %s[%d] = {%s};" % ("static " if static else "", name, len(data),
                                               ", ".join("0x%04x" % v for v in data))


class Bank:
    """The well's tile bank: 8x8 tiles as palette indices, shared by identical data (the map entry has the palette)."""

    def __init__(self):
        self.tiles = [[0] * 64]
        self.index = {tuple([0] * 64): 0}

    def add(self, idx):
        k = tuple(idx)
        if k not in self.index:
            self.index[k] = len(self.tiles)
            self.tiles.append(list(idx))
        return self.index[k]

    def cell(self, img, x0, y0, w, h, lut, pal):
        """the map entries of a w x h cell (row-major tiles), colours by lut (rgb555 -> index; transparent 0)"""
        c = rsasset.cell(img, x0, y0, w, h)
        out = []
        for ty in range(0, h, 8):
            for tx in range(0, w, 8):
                idx = []
                for y in range(8):
                    for x in range(8):
                        v = c[ty + y][tx + x]
                        if v is None:
                            idx.append(0)
                        else:
                            if v not in lut:
                                raise SystemExit("build_assets: colour %s of a cell at (%d, %d) is not in its palette"
                                                 % (rsasset.rgb888(v), x0 + tx + x, y0 + ty + y))
                            idx.append(lut[v])
                t = self.add(idx)
                out.append(rsasset.rs_map(VR_WELL_REL + t, pal) if t else 0)
        return out


VR_WELL_REL = 0     # the bank's tile numbers are relative to VR_WELL (the layers' tile base)


def lut_of(colours):
    return {rsasset.to555(c): i + 1 for i, c in enumerate(colours)}


def pal16(colours):
    return rsasset.palette16([rsasset.to555(c) for c in colours])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "sprites.png")):
        make_art.write_all(a.art)
    c = ["/* Generated by games/gopherdig/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/gopherdig/tools/build_assets.py. Do not edit. */",
         "#ifndef GM_ASSETS_H\n#define GM_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n",
         "#define VR_BG1 %d\n#define VR_WELL %d\n#define VR_OBJ %d\n#define KIT_OBJ_TILE %d\n#define BAR_TILE %d" %
         (VR_BG1, VR_WELL, VR_OBJ, KIT_OBJ_TILE, BAR_TILE),
         "#define PAL_BLOCK_A %d\n#define PAL_BLOCK_B %d\n#define PAL_STRATUM %d\n#define PAL_LOGO %d\n"
         "#define PAL_DECOR %d\n#define PAL_SURFACE %d" % (PAL_BLOCK_A, PAL_BLOCK_B, PAL_STRATUM, PAL_LOGO, PAL_DECOR,
                                                          PAL_SURFACE)]
    stats = []
    bank = Bank()

    # ---- the blocks: 4 colours x 4 quarters x 8 states -------------------------------------------------------------------
    blocks = rsasset.load(os.path.join(a.art, "tiles", "blocks.png"))
    pal_a = [make_art.BLOCK_OUT, make_art.SHINE] + make_art.BLOCK_RAMPS[0] + make_art.BLOCK_RAMPS[1]
    pal_b = [make_art.BLOCK_OUT, make_art.SHINE] + make_art.BLOCK_RAMPS[2] + make_art.BLOCK_RAMPS[3]
    q = []
    for k in range(4):
        pal, lut = (PAL_BLOCK_A, lut_of(pal_a)) if k < 2 else (PAL_BLOCK_B, lut_of(pal_b))
        for i in range(32):
            q += bank.cell(blocks, i * 8, k * 8, 8, 8, lut, pal)
    c.append(arr("gm_block_q", q))
    h.append("extern const uint16_t gm_block_q[4 * 32];     /* colour * 32 + quarter (TL TR BL BR) * 8 + state */")

    # ---- the stratum cells (BG 3), the buried things (BG 6), the surface (BG 7) ----------------------------------------------
    well = rsasset.load(os.path.join(a.art, "tiles", "well.png"))
    lut0 = lut_of(make_art.P0)
    names, metas = [], []
    x = 0
    for name, w in make_art.WELL_CELLS:
        m = bank.cell(well, x, 0, w, 16, lut0, PAL_STRATUM)
        if w == 8:
            m = [m[0], 0, m[1], 0]
        names.append("CELL_%s" % name.upper())
        metas += m
        x += w
    surf = rsasset.load(os.path.join(a.art, "tiles", "surface.png"))
    sc = rsasset.cell(surf, 0, 0, surf.width, 16)
    surf_cols = sorted({v for row in sc for v in row if v is not None})
    assert len(surf_cols) <= 15, "the surface has more than 15 colours"
    lut_s = {v: i + 1 for i, v in enumerate(surf_cols)}
    x = 0
    for name, w in make_art.SURFACE_CELLS:
        metas += bank.cell(surf, x, 0, w, 16, lut_s, PAL_SURFACE)
        names.append("CELL_%s" % name.upper())
        x += w
    h.append("enum { %s, CELL_COUNT };" % ", ".join(names))
    h.append("extern const uint16_t gm_cell[CELL_COUNT][4];    /* 2x2 map entries (8-px-wide edges: [0], [2]) */")
    c.append("const uint16_t gm_cell[CELL_COUNT][4] = {%s};" %
             ", ".join("{0x%04x, 0x%04x, 0x%04x, 0x%04x}" % tuple(metas[i:i + 4]) for i in range(0, len(metas), 4)))
    decor = rsasset.load(os.path.join(a.art, "tiles", "decor.png"))
    dm = []
    for s in range(len(make_art.STRATA_PALS)):
        lut = lut_of(make_art.STRATA_PALS[s][:4] + make_art.DECOR_PALS[s])
        for i in range(make_art.DECOR_ITEMS):
            dm += bank.cell(decor, i * 16, s * 16, 16, 16, lut, PAL_DECOR)
    h.append("#define STRATA_ART %d\n#define DECOR_ITEMS %d" % (len(make_art.STRATA_PALS), make_art.DECOR_ITEMS))
    h.append("extern const uint16_t gm_decor[STRATA_ART][DECOR_ITEMS][4];")
    quads = ["{0x%04x, 0x%04x, 0x%04x, 0x%04x}" % tuple(dm[i:i + 4]) for i in range(0, len(dm), 4)]
    n = make_art.DECOR_ITEMS
    c.append("const uint16_t gm_decor[STRATA_ART][DECOR_ITEMS][4] = {%s};" %
             ", ".join("{%s}" % ", ".join(quads[i:i + n]) for i in range(0, len(quads), n)))

    # palettes
    c.append(arr("gm_block_pals", pal16(pal_a) + pal16(pal_b)))
    c.append(arr("gm_surface_pal", rsasset.palette16(surf_cols)))
    sp, dp = [], []
    for s in range(len(make_art.STRATA_PALS)):
        sp += pal16(make_art.STRATA_PALS[s])
        dp += pal16(make_art.STRATA_PALS[s][:4] + make_art.DECOR_PALS[s])
    c.append(arr("gm_strata_pal", sp))
    c.append(arr("gm_decor_pal", dp))
    # the backdrop under the blocks' round corners: each stratum's back wall (mid), and its earth (light) for previews
    h.append("extern const uint16_t gm_block_pals[32];\nextern const uint16_t gm_surface_pal[16];")
    h.append("extern const uint16_t gm_strata_pal[STRATA_ART * 16];\nextern const uint16_t gm_decor_pal[STRATA_ART * 16];")
    c.append(rsasset.c_bytes("gm_well_tiles", rsasset.tiles_bytes(bank.tiles)))
    c.append("const int gm_well_tile_count = %d;" % len(bank.tiles))
    h.append("extern const uint8_t gm_well_tiles[];\nextern const int gm_well_tile_count;")
    assert VR_WELL + len(bank.tiles) <= VR_OBJ, "the well's tiles overlap the sprites"
    stats.append("WELL %d" % len(bank.tiles))

    # ---- sprites ----------------------------------------------------------------------------------------------------
    sheet = rsasset.load(os.path.join(a.art, "sprites.png"))
    tiles, rows, enames, pals = [], [], [], [0] * 128
    idx = 0
    for g in ("hero", "props", "crumbs"):
        ents = [e for e in make_art.SPRITES if e[6] == g]
        frames = []
        for name, x, y, w, hh, n, _g in ents:
            frames += [rsasset.cell(sheet, x + i * w, y, w, hh) for i in range(n)]
        ro = rsasset.convert_obj(frames)
        p16 = rsasset.palette16(ro.palette)
        pals[OBJ_PAL[g] * 16:OBJ_PAL[g] * 16 + 16] = p16
        if g == "hero":
            rgb = [rsasset.rgb888(v) for v in p16[1:]]
            sw = hs.player_palettes(rgb, *P2_HUE)               # [P1, P2, P3, P4]
            for p, slot in ((1, 1), (2, 4), (3, 5)):
                pals[slot * 16:slot * 16 + 16] = [0] + [rsasset.to555(v) for v in sw[p]]
        k = 0
        for name, x, y, w, hh, n, _g in ents:
            enames.append("SPR_%s = %d" % (name.upper(), idx))
            for f in range(n):
                first, fw, fh = ro.frames[k]
                rows.append("{%d, %d, %d, %d}" % (len(tiles) + first, fw, fh, OBJ_PAL[g]))
                k += 1
                idx += 1
        tiles += ro.tiles
    assert len(tiles) <= KIT_OBJ_TILE, "the sprites overlap the kit's tiles: raise KIT_OBJ_TILE"
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(enames), idx))
    h.append("typedef struct gm_sprite_def { uint16_t tile; uint8_t w, h, pal; } gm_sprite_def;")
    h.append("extern const gm_sprite_def gm_spr[SPR_COUNT];")
    h.append("extern const uint8_t gm_obj_tiles[];\nextern const int gm_obj_tile_count;\nextern const uint16_t gm_obj_pals[128];")
    c.append("const gm_sprite_def gm_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("gm_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gm_obj_tile_count = %d;" % len(tiles))
    c.append(rsasset.c_u16("gm_obj_pals", pals))
    stats.append("OBJ %d" % len(tiles))

    # ---- the asset pack: the music ------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        data = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, data, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(data)))
    c.append("const rs_asset_entry gm_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry gm_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: tiles %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
