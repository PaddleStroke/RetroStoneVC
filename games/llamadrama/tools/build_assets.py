#!/usr/bin/env python3
"""Llama Drama asset build: the code-drawn sheets (make_art.py) -> tiles, palettes (with their sunset, dusk and night
versions), maps and sprites; the music (make_music.py) -> build/gen/llamadrama/assets.c + assets.h.

    build_assets.py --out build/gen/llamadrama [--art games/llamadrama/art] [--tileset IGNORED]

MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/llamadrama/LICENSE.
"""
import argparse
import glob
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "games", "common", "tools"))
import rsasset  # noqa: E402
import make_art  # noqa: E402

# BG palettes: 0 the UI (the kit), 1 the meadow, 2 the mountains, 5 the logo (the kit)
PAL_MEADOW, PAL_MTN, PAL_LOGO = 1, 2, 5
# OBJ palettes: 0 the llama (P1), 1 P2, 2 the hornets, 3 the kit, 4 P3, 5 P4, 6 the props, 7 the sky (by the time of day)
OBJ_PAL = {"llama": 0, "hornets": 2, "props": 6, "sky": 7}
PLAYER_SLOTS = {1: 1, 2: 4, 3: 5}
# BG1 the UI (the kit: 0..767 with the glyph pool), BG2 the scenery (the mountains and the meadow, two palettes)
VR_BG1, VR_BG2, VR_OBJ = 0, 1024, 3072
KIT_OBJ_TILE = 576                                        # the kit's sprites (house_ui.h HU_OBJ_TILES) after ours
TIMES = 4                                                 # the day, the sunset, the dusk, the night


def cells8(img, x0, y0, w, h):
    return [rsasset.cell(img, x0 + x * 8, y0 + y * 8, 8, 8) for y in range(h // 8) for x in range(w // 8)]


def arr(name, data):
    return "const uint16_t %s[%d] = {%s};" % (name, len(data), ", ".join("0x%04x" % v for v in data))


def remap(p16, mapping):
    """p16 (RGB555, entry 0 transparent) with the colours of mapping (RGB888 -> RGB888) replaced."""
    m = {rsasset.to555(a): rsasset.to555(b) for a, b in mapping.items()}
    return [m.get(v, v) if i else v for i, v in enumerate(p16)]


def clamp(v):
    return max(0, min(255, int(round(v))))


def time_of_day(rgb, k, kind="land"):
    """A colour at time k (0 day, 1 sunset, 2 dusk, 3 night): the scenery warms, turns violet, then night blue."""
    r, g, b = rgb
    if k == 0:
        return rgb
    if kind == "sun":                                     # the sun turns orange as it sets
        return (clamp(r), clamp(g * [1, 0.8, 0.62, 0.5][k]), clamp(b * [1, 0.55, 0.4, 0.3][k]))
    if kind == "moon":
        return rgb
    if k == 1:
        return (clamp(r * 1.04 + 14), clamp(g * 0.84 + 6), clamp(b * 0.72 + 12))
    if k == 2:
        return (clamp(r * 0.64 + 22), clamp(g * 0.54 + 12), clamp(b * 0.72 + 34))
    return (clamp(r * 0.32 + 8), clamp(g * 0.38 + 14), clamp(b * 0.56 + 34))


def tod_palettes(p16, kinds=None):
    """The palette's 4 times of day, 16 entries each (entry 0 stays transparent)."""
    out = []
    for k in range(TIMES):
        for i, v in enumerate(p16):
            if i == 0:
                out.append(0)
                continue
            rgb = rsasset.rgb888(v)
            kind = (kinds or {}).get(rgb, "land")
            out.append(v if kind == "fixed" else rsasset.to555(time_of_day(rgb, k, kind)))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "sprites.png")):
        make_art.write_all(a.art)
    c = ["/* Generated by games/llamadrama/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/llamadrama/tools/build_assets.py. Do not edit. */",
         "#ifndef GM_ASSETS_H\n#define GM_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n",
         "#define VR_BG1 %d\n#define VR_BG2 %d\n#define VR_OBJ %d\n#define KIT_OBJ_TILE %d" %
         (VR_BG1, VR_BG2, VR_OBJ, KIT_OBJ_TILE),
         "#define PAL_MEADOW %d\n#define PAL_MTN %d\n#define PAL_LOGO %d\n#define PAL_SKY %d\n#define TIMES %d" %
         (PAL_MEADOW, PAL_MTN, PAL_LOGO, OBJ_PAL["sky"], TIMES)]
    stats = []

    # ---- BG2: the mountains (rows from MOUNTAINS_Y) and the meadow (from MEADOW_Y), one palette each ---------------
    ntiles, all_tiles = 0, []
    for key, pal in (("mountains", PAL_MTN), ("meadow", PAL_MEADOW)):
        f, w, hh = make_art.PANORAMAS[key]
        img = rsasset.load(os.path.join(a.art, f))
        r = rsasset.convert_bg(cells8(img, 0, 0, w, hh), 1, pal_base=pal, tile_base=ntiles,
                               reserve_blank=(key == "mountains"))
        assert len(r.palettes) == 1, key
        all_tiles += r.tiles
        ntiles += len(r.tiles)
        up = key.upper()
        y0 = make_art.MOUNTAINS_Y if key == "mountains" else make_art.MEADOW_Y
        c.append(arr("gm_%s_map" % key, [m[0] for m in r.metas]))
        p16 = rsasset.palette16(r.palettes[0])
        c.append(arr("gm_%s_pals" % key, tod_palettes(p16, {make_art.STARC: "fixed"})))
        h.append("#define %s_W %d\n#define %s_H %d\n#define %s_ROW %d" % (up, w // 8, up, hh // 8, up, y0 // 8))
        h.append("extern const uint16_t gm_%s_map[%s_W * %s_H];" % (key, up, up))
        h.append("extern const uint16_t gm_%s_pals[TIMES * 16];" % key)
        if key == "mountains":
            h.append("#define IDX_STAR %d" % (r.palettes[0].index(rsasset.to555(make_art.STARC)) + 1))
        stats.append("%s %d" % (key, len(r.tiles)))
    c.append(rsasset.c_bytes("gm_bg2_tiles", rsasset.tiles_bytes(all_tiles)))
    c.append("const int gm_bg2_tile_count = %d;" % len(all_tiles))
    h.append("extern const uint8_t gm_bg2_tiles[];\nextern const int gm_bg2_tile_count;")

    # ---- sprites ----------------------------------------------------------------------------------------------------
    sheet = rsasset.load(os.path.join(a.art, "sprites.png"))
    tiles, rows, names, pals = [], [], [], [0] * 128
    idx = 0
    for g in ("llama", "hornets", "props", "sky"):
        ents = [e for e in make_art.SPRITES if e[6] == g]
        frames = []
        for name, x, y, w, hh, n, _g in ents:
            frames += [rsasset.cell(sheet, x + i * w, y, w, hh) for i in range(n)]
        cols = set()
        for fr in frames:
            cols |= rsasset.colors_of(fr)
        assert len(cols) <= 15, (g, len(cols), sorted(rsasset.rgb888(v) for v in cols))
        ro = rsasset.convert_obj(frames)
        p16 = rsasset.palette16(ro.palette)
        pals[OBJ_PAL[g] * 16:OBJ_PAL[g] * 16 + 16] = p16
        if g == "llama":                                     # players 2-4: the wool and the tassels recoloured
            for p, slot in PLAYER_SLOTS.items():
                m = dict(zip(make_art.FUR, make_art.FUR_P[p]))
                m.update(zip(make_art.ACC, make_art.ACC_P[p]))
                pals[slot * 16:slot * 16 + 16] = remap(p16, m)
        if g == "sky":
            kinds = {rgb: "sun" for rgb in make_art.SUN}
            kinds.update({rgb: "moon" for rgb in make_art.MOON})
            c.append(arr("gm_sky_pals", tod_palettes(p16, kinds)))
            h.append("extern const uint16_t gm_sky_pals[TIMES * 16];")
        k = 0
        for name, x, y, w, hh, n, _g in ents:
            names.append("SPR_%s = %d" % (name.upper(), idx))
            for f in range(n):
                first, fw, fh = ro.frames[k]
                rows.append("{%d, %d, %d, %d}" % (len(tiles) + first, fw, fh, OBJ_PAL[g]))
                k += 1
                idx += 1
        tiles += ro.tiles
    assert len(tiles) <= KIT_OBJ_TILE, "the sprites (%d tiles) overlap the kit's tiles: raise KIT_OBJ_TILE" % len(tiles)
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(names), idx))
    h.append("#define HEAD_FRAMES %d\n#define NECK_FRAMES %d" % (len(make_art.HEAD_ANGLES), len(make_art.NECK_LEANS)))
    h.append("typedef struct gm_sprite_def { uint16_t tile; uint8_t w, h, pal; } gm_sprite_def;")
    h.append("extern const gm_sprite_def gm_spr[SPR_COUNT];")
    h.append("extern const uint8_t gm_obj_tiles[];\nextern const int gm_obj_tile_count;\nextern const uint16_t gm_obj_pals[128];")
    c.append("const gm_sprite_def gm_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("gm_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gm_obj_tile_count = %d;" % len(tiles))
    c.append(rsasset.c_u16("gm_obj_pals", pals))
    stats.append("OBJ %d" % len(tiles))

    # ---- the asset pack: the music ------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        data = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, data, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(data)))
    c.append("const rs_asset_entry gm_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry gm_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: tiles %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
