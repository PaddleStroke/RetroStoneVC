#!/usr/bin/env python3
"""Goat Gorge asset build: the code-drawn art (art/*.png, indexed: make_art.py), the rooms (levels/*.txt), the recorded
solutions and the music (make_music.py) -> build/gen/goatgorge/assets.c + assets.h.

    build_assets.py --out build/gen/goatgorge [--art games/goatgorge/art] [--tileset IGNORED]

The PNGs' pixels are palette indices (0 clear): they become 4-bpp tiles as they are, every chapter colouring the same
terrain tiles with its own palette. The rooms and solutions go into the asset pack as text (rs_asset: a data folder's
copy wins, so the rooms can be edited without rebuilding).

MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/goatgorge/LICENSE.
"""
import argparse
import glob
import os
import subprocess
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
import rsasset  # noqa: E402
import make_art as art  # noqa: E402

PAL_UI, PAL_TERRAIN, PAL_PROPS, PAL_LOGO, PAL_MID, PAL_FAR = 0, 1, 2, 5, 6, 7
VR_BG1, VR_BG2, VR_BG3, VR_BG4, VR_OBJ = 0, 1024, 1280, 1792, 3072
KIT_OBJ_TILE = 640                      # the kit's sprites (house_ui.h HU_OBJ_TILES) after ours
OBJ_PALS = {"kid": 0, "kid_nodash": 1, "prop": 2, "trail": 4, "fx": 5}


def indices(path):
    im = Image.open(path)
    assert im.mode == "P", "%s must be an indexed PNG (make_art.py)" % path
    w, hh = im.size
    d = list(im.getdata())
    return [[d[y * w + x] & 15 for x in range(w)] for y in range(hh)], w, hh


def tile_at(px, x0, y0):
    return [px[y0 + y][x0 + x] for y in range(8) for x in range(8)]


def bg_layer(px, w, hh, pal):
    """an indexed picture -> (tiles, map): the duplicate tiles (also flipped) shared, tile 0 blank"""
    tiles, index, mp = [[0] * 64], {tuple([0] * 64): (0, 0, 0)}, []
    for ty in range(hh // 8):
        for tx in range(w // 8):
            t = tile_at(px, tx * 8, ty * 8)
            key = tuple(t)
            if key not in index:
                hf = rsasset.hflip(t)
                found = None
                for cand, f in ((tuple(hf), (1, 0)), (tuple(rsasset.vflip(t)), (0, 1)), (tuple(rsasset.vflip(hf)), (1, 1))):
                    if cand in index:
                        n, fa, fb = index[cand]
                        found = (n, fa ^ f[0], fb ^ f[1])
                        break
                if found is None:
                    index[key] = (len(tiles), 0, 0)
                    tiles.append(t)
                else:
                    index[key] = found
            n, fa, fb = index[key]
            mp.append(rsasset.rs_map(n, pal, 0, fa, fb))
    return tiles, mp


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "sprites.png")):
        art.write_all(a.art)
    c = ["/* Generated by games/goatgorge/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/goatgorge/tools/build_assets.py. Do not edit. */",
         "#ifndef GG_ASSETS_H\n#define GG_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n",
         "#define VR_BG1 %d\n#define VR_BG2 %d\n#define VR_BG3 %d\n#define VR_BG4 %d\n#define VR_OBJ %d\n#define KIT_OBJ_TILE %d"
         % (VR_BG1, VR_BG2, VR_BG3, VR_BG4, VR_OBJ, KIT_OBJ_TILE),
         "#define PAL_UI %d\n#define PAL_TERRAIN %d\n#define PAL_PROPS %d\n#define PAL_LOGO %d\n#define PAL_MID %d\n"
         "#define PAL_FAR %d" % (PAL_UI, PAL_TERRAIN, PAL_PROPS, PAL_LOGO, PAL_MID, PAL_FAR),
         "#define CHAPTER_COUNT %d" % art.CHAPTERS]
    stats = []
    to555 = rsasset.to555

    # ---- the terrain: one set of tiles, a palette per chapter (and the props' palette: ledges, crumbling blocks)
    px, w, hh = indices(os.path.join(a.art, "terrain.png"))
    _tiles, names = art.build_tiles()
    tt = [tile_at(px, (i % 16) * 8, (i // 16) * 8) for i in range(len(names))]
    c.append(rsasset.c_bytes("gg_terrain_tiles", rsasset.tiles_bytes(tt)))
    c.append("const int gg_terrain_tile_count = %d;" % len(tt))
    h.append("extern const uint8_t gg_terrain_tiles[];\nextern const int gg_terrain_tile_count;")
    for i, n in enumerate(names):
        h.append("#define TT_%s %d" % (n.upper(), i))
    pals = []
    for ch in range(art.CHAPTERS):
        pals += [0] + [to555(col) for col in art.TERRAIN[ch]]
    c.append(rsasset.c_u16("gg_terrain_pal", pals))
    c.append(rsasset.c_u16("gg_props_pal", [0] + [to555(col) for col in art.PROPS[:15]]))
    h.append("extern const uint16_t gg_terrain_pal[%d * 16];\nextern const uint16_t gg_props_pal[16];" % art.CHAPTERS)
    stats.append("terrain %d" % len(tt))

    # ---- the sky, the far and middle layers, by chapter
    sky = []
    for top, bottom in art.SKY:
        sky += [to555(top), to555(bottom)]
    c.append(rsasset.c_u16("gg_sky", sky))
    h.append("extern const uint16_t gg_sky[%d * 2];" % art.CHAPTERS)
    for kind, pal, cols in (("far", PAL_FAR, art.FAR), ("mid", PAL_MID, art.MID)):
        tiles_all, maps_all, counts, offs = [], [], [], []
        mw = mh = 0
        for ch in range(art.CHAPTERS):
            px, mw, mh = indices(os.path.join(a.art, "%s_ch%d.png" % (kind, ch + 1)))
            tiles, mp = bg_layer(px, mw, mh, pal)
            offs.append(len(tiles_all))
            counts.append(len(tiles))
            tiles_all += tiles
            maps_all += mp
        c.append(rsasset.c_bytes("gg_%s_tiles" % kind, rsasset.tiles_bytes(tiles_all)))
        c.append("const int gg_%s_tile_off[%d] = {%s};" % (kind, art.CHAPTERS, ", ".join(map(str, offs))))
        c.append("const int gg_%s_tile_count[%d] = {%s};" % (kind, art.CHAPTERS, ", ".join(map(str, counts))))
        c.append(rsasset.c_u16("gg_%s_map" % kind, maps_all))
        pl = []
        for ch in range(art.CHAPTERS):
            pl += ([0] + [to555(col) for col in cols[ch]] + [0] * 16)[:16]
        c.append(rsasset.c_u16("gg_%s_pal" % kind, pl))
        up = kind.upper()
        h.append("#define %s_W %d\n#define %s_H %d" % (up, mw // 8, up, mh // 8))
        h.append("extern const uint8_t gg_%s_tiles[];\nextern const int gg_%s_tile_off[%d], gg_%s_tile_count[%d];"
                 % (kind, kind, art.CHAPTERS, kind, art.CHAPTERS))
        h.append("extern const uint16_t gg_%s_map[%d * %s_W * %s_H];\nextern const uint16_t gg_%s_pal[%d * 16];"
                 % (kind, art.CHAPTERS, up, up, kind, art.CHAPTERS))
        stats.append("%s %s" % (kind, "/".join(map(str, counts))))

    # ---- sprites: each frame's tiles consecutive (row-major)
    px, w, hh = indices(os.path.join(a.art, "sprites.png"))
    tiles, rows, names2 = [], [], []
    idx = 0
    for name, x, y, fw, fh, n, pal in art.SPRITES:
        names2.append("SPR_%s = %d" % (name.upper(), idx))
        for f in range(n):
            first = len(tiles)
            for ty in range(fh // 8):
                for tx in range(fw // 8):
                    tiles.append(tile_at(px, x + f * fw + tx * 8, y + ty * 8))
            rows.append("{%d, %d, %d, %d}" % (first, fw, fh, pal))
            idx += 1
    assert len(tiles) <= KIT_OBJ_TILE, "the sprites overlap the kit's tiles: raise KIT_OBJ_TILE"
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(names2), idx))
    h.append("typedef struct gg_sprite_def { uint16_t tile; uint8_t w, h, pal; } gg_sprite_def;")
    h.append("extern const gg_sprite_def gg_spr[SPR_COUNT];")
    c.append("const gg_sprite_def gg_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("gg_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gg_obj_tile_count = %d;" % len(tiles))
    opal = [0] * 128
    for key, slot in OBJ_PALS.items():
        cols = getattr(art, key.upper())
        opal[slot * 16:slot * 16 + 16] = ([0] + [to555(col) for col in cols[:15]] + [0] * 16)[:16]
    c.append(rsasset.c_u16("gg_obj_pals", opal))
    h.append("extern const uint8_t gg_obj_tiles[];\nextern const int gg_obj_tile_count;\n"
             "extern const uint16_t gg_obj_pals[128];")
    stats.append("OBJ %d" % len(tiles))

    # ---- the asset pack: the rooms, the solutions, the music
    pack = []
    for p in sorted(glob.glob(os.path.join(GAME, "levels", "*.txt"))):
        pack.append(("levels/" + os.path.basename(p), open(p, "rb").read()))
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    for p in sorted(glob.glob(os.path.join(music_dir, "*.mod"))):
        pack.append(("music/" + os.path.basename(p), open(p, "rb").read()))
    entries = []
    for i, (name, data) in enumerate(pack):
        c.append(rsasset.c_bytes("pack_%d" % i, data, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(data)))
    c.append("const rs_asset_entry gg_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry gg_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: tiles %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
