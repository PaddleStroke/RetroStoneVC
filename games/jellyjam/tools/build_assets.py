#!/usr/bin/env python3
"""Jelly Jam asset build: the code-drawn sheets (make_art.py) -> the jelly pictures (palette indices, for draw.c's
software painter), the kitchen's tiles and palettes, the sprites, the chefs; the music (make_music.py)
-> build/gen/jellyjam/assets.c + assets.h.

    build_assets.py --out build/gen/jellyjam [--art games/jellyjam/art] [--tileset IGNORED]

VRAM (tiles of 32 bytes): BG1 the UI at 0 (the kit 0..296, the logo 320..639, the glyph pool 640..767), BG2 the
fields' pictures at 768 (tile 0 blank, the rest handed out as the jellies need them, up to 1000), BG3 the kitchen at
1792, the sprites at 2048 (ours, the chef's slot, then the kit's).
BG palettes: 0 the UI, 1 the wall, 2 the fields' frames, 3 the jellies, 4 the wood and the jars, 5 the logo.
OBJ palettes: 0, 1, 4, 5 the players' heroes, 3 the kit, 6 the jellies (props), 7 the chef of the duel.

MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/jellyjam/LICENSE.
"""
import argparse
import glob
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "games", "common", "tools"))
import rsasset  # noqa: E402
import house_style as hs  # noqa: E402
import make_art as ma  # noqa: E402

PAL_WALL, PAL_FIELD, PAL_JELLY, PAL_JARS, PAL_LOGO = 1, 2, 3, 4, 5
BG_PAL_OF = {"wall": PAL_WALL, "field": PAL_FIELD, "jars": PAL_JARS}
OBJ_PAL = {"hero": 0, "props": 6}                         # OBJ 1, 4, 5: heroes 2-4; 3: the kit; 7: the chef
VR_BG1, VR_BG2, VR_BG3, VR_OBJ = 0, 768, 1792, 2048
FIELD_TILES = 1000                                        # BG2: the fields' tiles (1..999; 0 is blank)
CHEF_TILES = 48                                           # a chef: 3 frames of 32x32
# players 2-4: the hero's pinks turned (house_style.player_palettes: P2 blue, P3 and P4 the hues farthest from them)
P2_HUE = (0.80, 1.00, -0.45)


def index_of(img_px, x, y, pal):
    """the palette index (1..15) of a sheet pixel, 0 for the magenta background"""
    c = img_px[x, y][:3]
    if c == hs.MAGENTA:
        return 0
    if c in pal:
        return pal.index(c) + 1
    best = min(range(len(pal)), key=lambda i: sum((a - b) ** 2 for a, b in zip(c, pal[i])))
    return best + 1


def pixels(im, x0, y0, w, h, pal):
    px = im.load()
    return [index_of(px, x0 + x, y0 + y, pal) for y in range(h) for x in range(w)]


def tiles_of(pix, w, h):
    """a w x h picture of indices -> its 8x8 tiles, row-major"""
    out = []
    for ty in range(h // 8):
        for tx in range(w // 8):
            out.append([pix[(ty * 8 + y) * w + tx * 8 + x] for y in range(8) for x in range(8)])
    return out


def pal16(cols):
    return rsasset.palette16([rsasset.to555(c) for c in cols])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "jellies.png")):
        ma.write_all(a.art)
    from PIL import Image
    c = ["/* Generated by games/jellyjam/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/jellyjam/tools/build_assets.py. Do not edit. */",
         "#ifndef GM_ASSETS_H\n#define GM_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n",
         "#define VR_BG1 %d\n#define VR_BG2 %d\n#define VR_BG3 %d\n#define VR_OBJ %d\n#define FIELD_TILES %d" %
         (VR_BG1, VR_BG2, VR_BG3, VR_OBJ, FIELD_TILES),
         "#define PAL_WALL %d\n#define PAL_FIELD %d\n#define PAL_JELLY %d\n#define PAL_JARS %d\n#define PAL_LOGO %d" %
         (PAL_WALL, PAL_FIELD, PAL_JELLY, PAL_JARS, PAL_LOGO)]
    stats = []

    # ---- the jellies: bodies by size, colour and joins; faces by size, colour and mood (palette indices) -------------
    im = Image.open(os.path.join(a.art, "jellies.png")).convert("RGB")
    pos, _W, _H = ma.jelly_layout()
    for S in ma.SIZES:
        bodies, faces = [], []
        for k in range(5):
            for m in range(16):
                key = ("b", S, k, m if k < 4 else 0)
                bodies.append(pixels(im, pos[key][0], pos[key][1], S, S, ma.JELLY_PAL))
            for d in range(3):
                key = ("f", S, k, d)
                faces.append(pixels(im, pos[key][0], pos[key][1], S, S, ma.JELLY_PAL))
        c.append(rsasset.c_bytes("gm_jelly%d" % S, [v for b in bodies for v in b]))
        c.append(rsasset.c_bytes("gm_face%d" % S, [v for f in faces for v in f]))
        h.append("extern const uint8_t gm_jelly%d[5 * 16 * %d * %d];   /* [colour 0..4][joins][y][x] */" % (S, S, S))
        h.append("extern const uint8_t gm_face%d[5 * 3 * %d * %d];     /* [colour][mood][y][x] */" % (S, S, S))
    c.append(rsasset.c_u16("gm_jelly_pal", pal16(ma.JELLY_PAL)))
    h.append("extern const uint16_t gm_jelly_pal[16];")
    h.append("#define JELLY_OUTLINE 1\n#define JELLY_WHITE 2")

    # ---- the kitchen: BG3 tiles and their palettes ------------------------------------------------------------------
    kim = Image.open(os.path.join(a.art, "tiles", "kitchen.png")).convert("RGB")
    kpos, _kw, _kh = ma.kitchen_layout()
    tiles = ma.kitchen_tiles()
    names = sorted(tiles)
    kt, kpal = [[0] * 64], []
    for n in names:
        pname = tiles[n][1]
        kt.append(pixels(kim, kpos[n][0], kpos[n][1], 8, 8, ma.KITCHEN_PALS[pname]))
        kpal.append(BG_PAL_OF[pname])
    c.append(rsasset.c_bytes("gm_kitchen_tiles", rsasset.tiles_bytes(kt)))
    c.append("const int gm_kitchen_tile_count = %d;" % len(kt))
    c.append("const uint8_t gm_kitchen_pal_of[%d] = {0, %s};" % (len(kt), ", ".join(str(p) for p in kpal)))
    c.append(rsasset.c_u16("gm_kitchen_pals", pal16(ma.WALL) + pal16(ma.FIELD) + pal16(ma.JARS_PAL)))
    h.append("enum { %s, KT_COUNT = %d };" % (", ".join("KT_%s = %d" % (n.upper(), i + 1) for i, n in enumerate(names)), len(kt)))
    h.append("extern const uint8_t gm_kitchen_tiles[];\nextern const int gm_kitchen_tile_count;")
    h.append("extern const uint8_t gm_kitchen_pal_of[KT_COUNT];\nextern const uint16_t gm_kitchen_pals[48];  /* wall, field, jars */")
    h.append("#define BACKDROP_RGB 0x%02x%02x%02x" % ma.BACKDROP)
    stats.append("BG3 %d" % len(kt))

    # ---- sprites: the hero (OBJ 0, players 2-4 turned), the props (OBJ 6) -------------------------------------------
    sim = Image.open(os.path.join(a.art, "sprites.png")).convert("RGB")
    allspr = {}
    for _g, cvs, _p in ma.sprite_sets():
        allspr.update(cvs)
    spos, _ = ma.pack(allspr)
    otiles, rows, enames = [], [], []
    pals = [0] * 128
    for g, cvs, pal in ma.sprite_sets():
        p16 = pal16(pal)
        pals[OBJ_PAL[g] * 16:OBJ_PAL[g] * 16 + 16] = p16
        if g == "hero":
            sw = hs.player_palettes(pal, *P2_HUE)              # [P1, P2, P3, P4]
            for p, slot in ((1, 1), (2, 4), (3, 5)):
                pals[slot * 16:slot * 16 + 16] = pal16(sw[p])
        for n in sorted(cvs):
            x, y, w, hh = spos[n]
            first = len(otiles)
            otiles += tiles_of(pixels(sim, x, y, w, hh, pal), w, hh)
            enames.append("SPR_%s = %d" % (n.upper(), len(rows)))
            rows.append("{%d, %d, %d, %d}" % (first, w, hh, OBJ_PAL[g]))
    chef_tile = (len(otiles) + 7) // 8 * 8
    kit_tile = chef_tile + CHEF_TILES
    h.append("#define CHEF_TILE %d\n#define CHEF_TILES %d\n#define KIT_OBJ_TILE %d" % (chef_tile, CHEF_TILES, kit_tile))
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(enames), len(rows)))
    h.append("typedef struct gm_sprite_def { uint16_t tile; uint8_t w, h, pal; } gm_sprite_def;")
    h.append("extern const gm_sprite_def gm_spr[SPR_COUNT];")
    h.append("extern const uint8_t gm_obj_tiles[];\nextern const int gm_obj_tile_count;\nextern const uint16_t gm_obj_pals[128];")
    c.append("const gm_sprite_def gm_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("gm_obj_tiles", rsasset.tiles_bytes(otiles)))
    c.append("const int gm_obj_tile_count = %d;" % len(otiles))
    c.append(rsasset.c_u16("gm_obj_pals", pals))
    stats.append("OBJ %d (+ the chef %d)" % (len(otiles), CHEF_TILES))

    # ---- the chefs: 3 frames each (idle, happy, dizzy), their palettes (loaded into OBJ 7 with the chef) -------------
    cim = Image.open(os.path.join(a.art, "chefs.png")).convert("RGB")
    cpos = ma.chef_layout()
    ct, cp = [], []
    for i in range(len(ma.CHEFS)):
        pal = ma.chef_palette(i)
        cp += pal16(pal)
        for m in ("idle", "happy", "dizzy"):
            x, y = cpos[(i, m)]
            ct += tiles_of(pixels(cim, x, y, 32, 32, pal), 32, 32)
    c.append(rsasset.c_bytes("gm_chef_tiles", rsasset.tiles_bytes(ct)))
    c.append(rsasset.c_u16("gm_chef_pals", cp))
    h.append("extern const uint8_t gm_chef_tiles[];        /* CHEF_TILES a chef: idle, happy, dizzy */")
    h.append("extern const uint16_t gm_chef_pals[%d];" % len(cp))

    # ---- the asset pack: the music ------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        data = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, data, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(data)))
    c.append("const rs_asset_entry gm_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry gm_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: tiles %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
