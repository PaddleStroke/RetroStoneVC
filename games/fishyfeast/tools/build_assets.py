#!/usr/bin/env python3
"""Fishy Feast asset build: the code-drawn sheets (make_art.py) -> tiles, palettes, maps, sprites and the fish parts
tables; the plankton specks' tiles; the music (make_music.py) -> build/gen/fishyfeast/assets.c + assets.h.

    build_assets.py --out build/gen/fishyfeast [--art games/fishyfeast/art] [--tileset IGNORED]

VRAM (tiles of 32 bytes): BG1 the UI at 0 (the kit 0..296, the logo 320..639, the glyph pool 640..767), BG2 the light
rays at 768, BG3 the plankton specks at 832, BG4 the pond floor at 896, the sprites at 1088 (the kit's after ours).

MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/fishyfeast/LICENSE.
"""
import argparse
import glob
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "games", "common", "tools"))
import rsasset  # noqa: E402
import house_style as hs  # noqa: E402
import make_art as ma  # noqa: E402

PAL_FLOOR, PAL_SPECKS, PAL_LOGO, PAL_RAYS = 1, 2, 5, 6          # BG palettes (the specks use 2, 3, 4)
VR_BG1, VR_BG2, VR_BG3, VR_BG4, VR_OBJ = 0, 768, 832, 896, 1088
# players 2-4: the goldfish's orange (and its ring) turned (house_style.player_palettes): P2 blue, P3, P4 the hues
# farthest from them
P2_HUE = (0.0, 0.2, 0.5)
# the bots' colours 0..7 -> (OBJ palette, variant): draw.c BOT_PAL
BOT_SLOTS = [(6, 0), (6, 1), (7, 0), (7, 1), (0, 1), (1, 1), (4, 1), (5, 1)]
SPECK_COLS = [[(232, 255, 110), (128, 196, 56)], [(255, 196, 228), (232, 96, 168)], [(214, 252, 255), (96, 196, 236)]]


def cells8(img, w, h):
    return [rsasset.cell(img, x * 8, y * 8, 8, 8) for y in range(h // 8) for x in range(w // 8)]


def arr16(name, data, kind="int16_t"):
    return "const %s %s[%d] = {%s};" % (kind, name, len(data), ", ".join(str(v) for v in data))


def fish_palettes():
    """The 8 OBJ palettes (16 RGB555 entries each; OBJ 2 the props, OBJ 3 left to the kit)."""
    pal = [[0] * 16 for _ in range(8)]
    ring_a = [ma.P1_RING] + list(ma.P1_RAMP)
    sw = hs.player_palettes(ring_a, *P2_HUE)                    # [P1, P2, P3, P4]: the ring and the A ramp
    bslot = {}
    for c, (slot, v) in enumerate(BOT_SLOTS):
        bslot.setdefault(slot, {})[v] = ma.BOT_RAMPS[c]
    for p, slot in enumerate((0, 1, 4, 5)):
        ring, ramp = sw[p][0], sw[p][1:]
        pal[slot] = [0] + [rsasset.to555(c) for c in ma.fish_palette(ring, ramp, bslot[slot][1])]
    for slot in (6, 7):
        pal[slot] = [0] + [rsasset.to555(c) for c in ma.fish_palette(ma.NAVY, bslot[slot][0], bslot[slot][1])]
    pal[2] = [0] + [rsasset.to555(c) for c in ma.PROPS_PAL]
    return pal


def specks_tiles():
    """The plankton specks: a dot at (ox, oy) on a 2-px grid, 3 sizes: 1 + size * 16 + (oy / 2) * 4 + ox / 2."""
    tiles = [[0] * 64]
    for size in range(3):
        for oy in range(0, 8, 2):
            for ox in range(0, 8, 2):
                t = [0] * 64

                def put(x, y, v):
                    if 0 <= x < 8 and 0 <= y < 8:
                        t[y * 8 + x] = v
                x0, y0 = min(ox, 8 - 2 - size), min(oy, 8 - 2 - size)      # the dot stays in its tile
                if size == 0:                       # far: 2x2
                    put(x0, y0, 1), put(x0 + 1, y0, 2), put(x0, y0 + 1, 2), put(x0 + 1, y0 + 1, 2)
                elif size == 1:                     # a 3x3 plus
                    put(x0 + 1, y0 + 1, 1), put(x0, y0 + 1, 2), put(x0 + 2, y0 + 1, 2), put(x0 + 1, y0, 2)
                    put(x0 + 1, y0 + 2, 2)
                else:                               # near: a round 4x4 with a bright core
                    for (x, y) in ((1, 0), (2, 0), (0, 1), (3, 1), (0, 2), (3, 2), (1, 3), (2, 3)):
                        put(x0 + x, y0 + y, 2)
                    put(x0 + 1, y0 + 1, 1), put(x0 + 2, y0 + 1, 1), put(x0 + 1, y0 + 2, 1), put(x0 + 2, y0 + 2, 2)
                tiles.append(t)
    return tiles


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "fish.png")):
        ma.write_all(a.art)
    c = ["/* Generated by games/fishyfeast/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/fishyfeast/tools/build_assets.py. Do not edit. */",
         "#ifndef GM_ASSETS_H\n#define GM_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n",
         "#define VR_BG1 %d\n#define VR_BG2 %d\n#define VR_BG3 %d\n#define VR_BG4 %d\n#define VR_OBJ %d" %
         (VR_BG1, VR_BG2, VR_BG3, VR_BG4, VR_OBJ),
         "#define PAL_FLOOR %d\n#define PAL_SPECKS %d\n#define PAL_LOGO %d\n#define PAL_RAYS %d" %
         (PAL_FLOOR, PAL_SPECKS, PAL_LOGO, PAL_RAYS)]
    stats = []

    # ---- BG4 the floor (64 x 64 tiles), BG2 the rays (32 x 32) -------------------------------------------------------
    for layer, f, n, name, pal in (("bg4", "tiles/floor.png", 64, "floor", PAL_FLOOR),
                                   ("bg2", "tiles/rays.png", 32, "rays", PAL_RAYS)):
        img = rsasset.load(os.path.join(a.art, f))
        r = rsasset.convert_bg(cells8(img, n * 8, n * 8), 1, pal_base=pal, tile_base=0)
        c.append(rsasset.c_bytes("gm_%s_tiles" % name, rsasset.tiles_bytes(r.tiles)))
        c.append("const int gm_%s_tile_count = %d;" % (name, len(r.tiles)))
        c.append(rsasset.c_u16("gm_%s_map" % name, [m[0] for m in r.metas]))
        c.append(rsasset.c_u16("gm_%s_pal" % name, rsasset.palette16(r.palettes[0])))
        h.append("#define %s_MAP %d" % (name.upper(), n))
        h.append("extern const uint8_t gm_%s_tiles[];\nextern const int gm_%s_tile_count;" % (name, name))
        h.append("extern const uint16_t gm_%s_map[%d];\nextern const uint16_t gm_%s_pal[16];" % (name, n * n, name))
        stats.append("%s %d" % (layer.upper(), len(r.tiles)))

    # ---- BG3 the plankton specks ----------------------------------------------------------------------------------------
    st = specks_tiles()
    c.append(rsasset.c_bytes("gm_specks_tiles", rsasset.tiles_bytes(st)))
    c.append("const int gm_specks_tile_count = %d;" % len(st))
    sp = []
    for light, dark in SPECK_COLS:
        sp += rsasset.palette16([rsasset.to555(light), rsasset.to555(dark)])
    c.append(rsasset.c_u16("gm_specks_pals", sp))
    h.append("extern const uint8_t gm_specks_tiles[];\nextern const int gm_specks_tile_count;")
    h.append("extern const uint16_t gm_specks_pals[48];")
    stats.append("BG3 %d" % len(st))

    # ---- sprites: the fish (their palette's indices), then the props --------------------------------------------------
    table, fs = ma.fish_parts()
    fsheet = rsasset.load(os.path.join(a.art, "fish.png"))
    fpos, _ = ma.pack(fs)
    psp = ma.props()
    psheet = rsasset.load(os.path.join(a.art, "props.png"))
    ppos, _ = ma.pack(psp)
    tiles, rows, names, ids = [], [], [], {}
    for group, pos, sheet, pal, objpal in (("fish", fpos, fsheet, ma.SHEET_PAL, 0),
                                          ("props", ppos, psheet, ma.PROPS_PAL, 2)):
        order = sorted(pos)
        frames = [rsasset.cell(sheet, *pos[n]) for n in order]
        ro = rsasset.convert_obj(frames, palette=[rsasset.to555(x) for x in pal])
        for k, n in enumerate(order):
            first, fw, fh = ro.frames[k]
            ids[n] = len(rows)
            names.append("SPR_%s = %d" % (n.upper(), len(rows)))
            rows.append("{%d, %d, %d, %d}" % (len(tiles) + first, fw, fh, objpal))
        tiles += ro.tiles
    kit_tile = (len(tiles) + 7) // 8 * 8
    h.append("#define KIT_OBJ_TILE %d" % kit_tile)
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(names), len(rows)))
    h.append("typedef struct gm_sprite_def { uint16_t tile; uint8_t w, h, pal; } gm_sprite_def;")
    h.append("extern const gm_sprite_def gm_spr[SPR_COUNT];")
    h.append("extern const uint8_t gm_obj_tiles[];\nextern const int gm_obj_tile_count;\n"
             "extern const uint16_t gm_obj_pals[128];")
    c.append("const gm_sprite_def gm_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("gm_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gm_obj_tile_count = %d;" % len(tiles))
    c.append(rsasset.c_u16("gm_obj_pals", [v for p in fish_palettes() for v in p]))
    stats.append("OBJ %d" % len(tiles))

    # ---- the fish parts: by variant and tier, front to back; the wag frames; pellets and urchins -------------------
    T = ma.TIERS
    MAXP = max(len(table[(v, R, 0)]) for v in (0, 1) for R in T)
    h.append("#define FISH_TIERS %d\n#define FISH_MAX_PARTS %d\n#define PELLET_TIERS 3\n#define URCHIN_TIERS %d" %
             (len(T), MAXP, len(ma.URCHIN_TIERS)))
    h.append("typedef struct gm_part { int16_t spr, ox, oy; uint8_t flags; } gm_part;   /* flags: 1 h-flip, 2 v-flip */")
    h.append("extern const uint8_t gm_tier_r[FISH_TIERS];\nextern const uint8_t gm_tier_nparts[FISH_TIERS];")
    h.append("extern const gm_part gm_fish_parts[2][FISH_TIERS][FISH_MAX_PARTS];")
    h.append("extern const int16_t gm_fish_wag[2][FISH_TIERS];")
    h.append("extern const uint8_t gm_pellet_r[PELLET_TIERS];\nextern const int16_t gm_pellet_spr[2][PELLET_TIERS];")
    h.append("extern const uint8_t gm_urchin_r[URCHIN_TIERS];\nextern const int16_t gm_urchin_spr[URCHIN_TIERS];")
    c.append("const uint8_t gm_tier_r[FISH_TIERS] = {%s};" % ", ".join(str(R) for R in T))
    c.append("const uint8_t gm_tier_nparts[FISH_TIERS] = {%s};" % ", ".join(str(len(table[(0, R, 0)])) for R in T))
    vs = []
    for v in (0, 1):
        ts = []
        for R in T:
            ps = ["{%d, %d, %d, %d}" % (ids[n], ox, oy, hf | (vf << 1)) for n, _cv, ox, oy, hf, vf in table[(v, R, 0)]]
            ps += ["{-1, 0, 0, 0}"] * (MAXP - len(ps))
            ts.append("{" + ", ".join(ps) + "}")
        vs.append("{" + ",\n     ".join(ts) + "}")
    c.append("const gm_part gm_fish_parts[2][FISH_TIERS][FISH_MAX_PARTS] = {\n    " + ",\n    ".join(vs) + "};")
    c.append("const int16_t gm_fish_wag[2][FISH_TIERS] = {%s};" % ", ".join(
        "{" + ", ".join(str(ids["fish_%s%dw" % ("ab"[v], R)]) if R in ma.WAG_TIERS else "-1" for R in T) + "}"
        for v in (0, 1)))
    c.append("const uint8_t gm_pellet_r[PELLET_TIERS] = {2, 3, 6};")
    c.append("const int16_t gm_pellet_spr[2][PELLET_TIERS] = {%s};" % ", ".join(
        "{" + ", ".join(str(ids["pellet_%s%d" % ("ab"[v], r)]) for r in (2, 3, 6)) + "}" for v in (0, 1)))
    c.append("const uint8_t gm_urchin_r[URCHIN_TIERS] = {%s};" % ", ".join(str(R) for R in ma.URCHIN_TIERS))
    c.append("const int16_t gm_urchin_spr[URCHIN_TIERS] = {%s};" % ", ".join(
        str(ids["urchin_%d" % R]) for R in ma.URCHIN_TIERS))
    h.append("#define BOT_SLOTS {%s}" % ", ".join("{%d, %d}" % s for s in BOT_SLOTS))

    # ---- the asset pack: the music ------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        data = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, data, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(data)))
    c.append("const rs_asset_entry gm_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry gm_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: tiles %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
