#!/usr/bin/env python3
"""Seal Shove asset build: the code-drawn sheets (make_art.py) -> sprites and palettes, the sea panorama -> tiles and
its map, the floe's canvas (which tiles of BG2 the floe can cover), the music (make_music.py)
-> build/gen/sealshove/assets.c + assets.h.

    build_assets.py --out build/gen/sealshove [--art games/sealshove/art] [--tileset IGNORED]

VRAM (tiles of 32 bytes): BG1 the UI at 0 (the kit 0..296, the title logo from 320); BG2 the floe's canvas from 320
too: the logo shows only on the title and the floe only in play, so they share those tiles (draw.c repaints the floe
when a run starts); the glyph pool of the translated texts at 896..1023; BG3 the sea at 1024; then the sprites, the
two drifting chunks' tiles and the kit's sprites.

MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/sealshove/LICENSE.
"""
import argparse
import glob
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "games", "common", "tools"))
import rsasset  # noqa: E402
import house_style as hs  # noqa: E402
import make_art as ma  # noqa: E402

PAL_ICE, PAL_SEA, PAL_LOGO = 1, 2, 5                      # BG palettes (the sea takes 2 and 3)
VR_BG1, VR_BG2, EXT_TILE, VR_BG3 = 0, 320, 896, 1024
OBJ_SEAL, OBJ_PROPS, OBJ_ICE, OBJ_PENG = 0, 2, 6, 7
DRIFT_SLOTS, DRIFT_SIZE = 2, 56                           # the chunks drifting away: 2 sprites of 56 x 56
# players 2-4: the hat and scarf (the reds) turned (house_style.player_palettes): P2 blue, P3 and P4 the hues
# farthest from them
P2_HUE = (0.0, 0.1, 0.58)


def game_h():
    """the floe's numbers, from src/game.h"""
    src = open(os.path.join(GAME, "src", "game.h")).read()
    v = {}
    for k in ("FLOE_CX", "FLOE_CY", "CELL", "GRID", "FLOE_R", "FLOE_JITTER"):
        v[k] = int(re.search(r"#define %s\s+(\d+)" % k, src).group(1))
    return v


def canvas_tiles():
    """The BG2 tiles the floe may cover (its rim, the side below it and the skirt): a canvas of GRID * CELL / 8 tiles a
    side from (GRID_X0, GRID_Y0); returns the index of each (0: none, never drawn) and the count."""
    g = game_h()
    n = g["GRID"] * g["CELL"] // 8
    x0, y0 = g["FLOE_CX"] - g["GRID"] * g["CELL"] // 2, g["FLOE_CY"] - g["GRID"] * g["CELL"] // 2
    reach = g["FLOE_R"] + g["FLOE_JITTER"] + 5
    idx, k = [], 0
    for ty in range(n):
        for tx in range(n):
            ax, ay = x0 + tx * 8, y0 + ty * 8
            dx = max(ax - g["FLOE_CX"], 0, g["FLOE_CX"] - (ax + 8))
            dy = max(ay - g["FLOE_CY"], 0, g["FLOE_CY"] - (ay + 8))
            if dx * dx + dy * dy <= reach * reach:
                k += 1
                idx.append(k)
            else:
                idx.append(0)
    return n, idx, k


def cells8(img, w, h):
    return [rsasset.cell(img, x * 8, y * 8, 8, 8) for y in range(h // 8) for x in range(w // 8)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "seals.png")):
        ma.write_all(a.art)
    c = ["/* Generated by games/sealshove/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/sealshove/tools/build_assets.py. Do not edit. */",
         "#ifndef GM_ASSETS_H\n#define GM_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n",
         "#define PAL_ICE %d\n#define PAL_SEA %d\n#define PAL_LOGO %d\n#define OBJ_PROPS %d\n#define OBJ_ICE %d\n"
         "#define OBJ_PENG %d" % (PAL_ICE, PAL_SEA, PAL_LOGO, OBJ_PROPS, OBJ_ICE, OBJ_PENG)]
    stats = []

    # ---- BG2: the floe's canvas ------------------------------------------------------------------------------------
    n, idx, count = canvas_tiles()
    assert VR_BG2 + 1 + count <= EXT_TILE, "the floe's canvas runs into the glyph pool"
    h.append("#define CANVAS_W %d\n#define CANVAS_TILES %d\n#define VR_BG1 %d\n#define VR_BG2 %d\n#define EXT_TILE %d\n"
             "#define VR_BG3 %d" % (n, count, VR_BG1, VR_BG2, EXT_TILE, VR_BG3))
    c.append("const int16_t gm_canvas_idx[%d] = {%s};" % (len(idx), ", ".join(str(v) for v in idx)))
    h.append("extern const int16_t gm_canvas_idx[CANVAS_W * CANVAS_W];   /* BG2 tile of each canvas cell (0: none) */")
    c.append(rsasset.c_u16("gm_ice_pal", rsasset.palette16([rsasset.to555(v) for v in ma.ICE_PAL])))
    h.append("extern const uint16_t gm_ice_pal[16];")
    stats.append("BG2 %d" % (count + 1))

    # ---- BG3: the sea panorama (128 x 32 tiles; stage x = its x - SEA_X0) ------------------------------------------------
    img = rsasset.load(os.path.join(a.art, "tiles", "sea.png"))
    r = rsasset.convert_bg(cells8(img, 1024, 256), 2, pal_base=PAL_SEA, tile_base=0)
    assert len(r.palettes) <= 2
    c.append(rsasset.c_bytes("gm_sea_tiles", rsasset.tiles_bytes(r.tiles)))
    c.append("const int gm_sea_tile_count = %d;" % len(r.tiles))
    c.append(rsasset.c_u16("gm_sea_map", [m[0] for m in r.metas]))
    pals = []
    for p in range(2):
        pals += rsasset.palette16(r.palettes[p]) if p < len(r.palettes) else [0] * 16
    c.append(rsasset.c_u16("gm_sea_pals", pals))
    cyc = []                                               # the ripples' colours (CGRAM indices), cycled by draw.c
    for key in ("r1", "r2", "sp"):
        v = rsasset.to555(ma.SEA[key])
        for p, pal in enumerate(r.palettes):
            if v in pal:
                cyc.append(((PAL_SEA + p) * 16 + pal.index(v) + 1, v))
    h.append("#define SEA_X0 %d\n#define SEA_CYCLE_N %d" % (ma.SEA_X0, len(cyc)))
    c.append("const uint16_t gm_sea_cycle[%d][2] = {%s};" % (max(1, len(cyc)), ", ".join("{%d, 0x%04x}" % e for e in cyc)
                                                               or "{0, 0}"))
    h.append("extern const uint8_t gm_sea_tiles[];\nextern const int gm_sea_tile_count;\n"
             "extern const uint16_t gm_sea_map[128 * 32];\nextern const uint16_t gm_sea_pals[32];\n"
             "extern const uint16_t gm_sea_cycle[][2];   /* CGRAM index, its colour */")
    stats.append("BG3 %d" % len(r.tiles))
    vr_obj = (VR_BG3 + len(r.tiles) + 7) // 8 * 8

    # ---- sprites: the seals, the props, the penguins -------------------------------------------------------------------
    tiles, rows, names = [], [], []
    for group, sprites, pal, objpal in (("seals", ma.seal_sprites(), ma.SEAL_PAL, OBJ_SEAL),
                                        ("props", ma.props(), ma.PROPS_PAL, OBJ_PROPS),
                                        ("penguins", ma.penguins(), ma.PENG_PAL, OBJ_PENG)):
        pos, _ = ma.pack(sprites, 64 if group == "penguins" else 256)
        sheet = rsasset.load(os.path.join(a.art, group + ".png"))
        order = sorted(pos)
        frames = [rsasset.cell(sheet, *pos[k]) for k in order]
        ro = rsasset.convert_obj(frames, palette=[rsasset.to555(x) for x in pal])
        for k, name in enumerate(order):
            first, fw, fh = ro.frames[k]
            names.append("SPR_%s = %d" % (name.upper(), len(rows)))
            rows.append("{%d, %d, %d, %d}" % (len(tiles) + first, fw, fh, objpal))
        tiles += ro.tiles
    drift_tile = (len(tiles) + 7) // 8 * 8
    dt = (DRIFT_SIZE // 8) ** 2
    kit_tile = drift_tile + DRIFT_SLOTS * dt
    h.append("#define VR_OBJ %d\n#define DRIFT_TILE %d\n#define DRIFT_SLOTS %d\n#define DRIFT_SIZE %d\n"
             "#define KIT_OBJ_TILE %d" % (vr_obj, drift_tile, DRIFT_SLOTS, DRIFT_SIZE, kit_tile))
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(names), len(rows)))
    h.append("typedef struct gm_sprite_def { uint16_t tile; uint8_t w, h, pal; } gm_sprite_def;")
    h.append("extern const gm_sprite_def gm_spr[SPR_COUNT];")
    h.append("extern const uint8_t gm_obj_tiles[];\nextern const int gm_obj_tile_count;\n"
             "extern const uint16_t gm_obj_pals[128];")
    c.append("const gm_sprite_def gm_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("gm_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gm_obj_tile_count = %d;" % len(tiles))
    opal = [[0] * 16 for _ in range(8)]
    sw = hs.player_palettes(ma.SEAL_PAL, *P2_HUE)                 # [P1, P2, P3, P4]
    for p, slot in enumerate((0, 1, 4, 5)):
        opal[slot] = [0] + [rsasset.to555(x) for x in sw[p]]
    opal[OBJ_PROPS] = rsasset.palette16([rsasset.to555(x) for x in ma.PROPS_PAL])
    opal[OBJ_ICE] = rsasset.palette16([rsasset.to555(x) for x in ma.ICE_PAL])
    opal[OBJ_PENG] = rsasset.palette16([rsasset.to555(x) for x in ma.PENG_PAL])
    c.append(rsasset.c_u16("gm_obj_pals", [v for p in opal for v in p]))
    stats.append("OBJ %d (+ %d drift)" % (len(tiles), DRIFT_SLOTS * dt))
    h.append("#define PENGUIN_N %d" % len(ma.PENGUINS))
    c.append("const int16_t gm_penguins[%d][2] = {%s};" % (len(ma.PENGUINS),
                                                           ", ".join("{%d, %d}" % p for p in ma.PENGUINS)))
    h.append("extern const int16_t gm_penguins[PENGUIN_N][2];   /* stage x, y of their feet */")

    # ---- the asset pack: the music ------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        data = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, data, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(data)))
    c.append("const rs_asset_entry gm_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry gm_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: tiles %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
