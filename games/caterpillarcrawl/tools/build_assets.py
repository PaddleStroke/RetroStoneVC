#!/usr/bin/env python3
"""Caterpillar Crawl asset build: the code-drawn sheets (make_art.py) -> tiles, palettes, maps and sprites; the music
(make_music.py) -> build/gen/caterpillarcrawl/assets.c + assets.h.

    build_assets.py --out build/gen/caterpillarcrawl [--art games/caterpillarcrawl/art] [--tileset IGNORED]

The layers: BG1 the UI (the house kit, VRAM 0..767 with the glyph pool), BG2 the caterpillars' bodies (its tile base is
the sprites' VRAM: a body segment is the 16x16 sprite's four tiles, on the BG palette of its player), BG3 the
obstacles (a transparent ground), BG4 the garden. The BG palettes: 0 the UI, 1-4 the players' bodies (the same colours
as their sprites: OBJ 0, 1, 4, 5), 5 the logo, 6 the garden, 7 the obstacles.

MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/caterpillarcrawl/LICENSE.
"""
import argparse
import colorsys
import glob
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "games", "common", "tools"))
import rsasset  # noqa: E402
import house_style as hs  # noqa: E402
import make_art  # noqa: E402

PAL_BODY, PAL_LOGO, PAL_GARDEN, PAL_OBST = 1, 5, 6, 7
OBJ_PAL = {"hero": 0, "props": 2, "small": 6}            # OBJ 3: the house kit sprites; OBJ 1, 4, 5: players 2-4
VR_BG1, VR_BG3, VR_BG4, VR_OBJ = 0, 1024, 1536, 3072
KIT_OBJ_TILE = 512                                        # the kit's sprites (house_ui.h HU_OBJ_TILES) after ours
# players 2-4: the caterpillar's greens turned (house_style.player_palettes: P2 pink, P3 and P4 the farthest hues)
P2_HUE = (0.16, 0.50, 0.62)
# P4's orange: the plain rotation lands the greens' hue spread on salmon lights and olive shadows; this ramp instead
# warms its lights towards yellow and its shadows towards red (the house ramps' rule), more saturated
P4_HUE, P4_SPREAD, P4_SAT = 0.075, -0.55, 1.3


def orange(rgbs, h_lo, h_hi):
    """Player 4's palette: the main material's hues around P4_HUE, their spread turned and squeezed."""
    h1 = hs.main_hue(rgbs, h_lo, h_hi)
    out = []
    for c in rgbs:
        h, l, s = colorsys.rgb_to_hls(*[v / 255.0 for v in c])
        if s > 0.25 and h_lo < h < h_hi:
            h, s = (P4_HUE + (h - h1) * P4_SPREAD) % 1.0, min(1.0, s * P4_SAT)
        out.append(tuple(int(round(v * 255)) for v in colorsys.hls_to_rgb(h, l, s)))
    return out


def cells8(img, x0, y0, w, h):
    return [rsasset.cell(img, x0 + x * 8, y0 + y * 8, 8, 8) for y in range(h // 8) for x in range(w // 8)]


def arr(name, data):
    return "const uint16_t %s[%d] = {%s};" % (name, len(data), ", ".join("0x%04x" % v for v in data))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "sprites.png")):
        make_art.write_all(a.art)
    c = ["/* Generated by games/caterpillarcrawl/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/caterpillarcrawl/tools/build_assets.py. Do not edit. */",
         "#ifndef GM_ASSETS_H\n#define GM_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n",
         "#define VR_BG1 %d\n#define VR_BG2 %d\n#define VR_BG3 %d\n#define VR_BG4 %d\n#define VR_OBJ %d\n"
         "#define KIT_OBJ_TILE %d" % (VR_BG1, VR_OBJ, VR_BG3, VR_BG4, VR_OBJ, KIT_OBJ_TILE),
         "#define PAL_BODY %d\n#define PAL_LOGO %d\n#define PAL_GARDEN %d\n#define PAL_OBST %d" %
         (PAL_BODY, PAL_LOGO, PAL_GARDEN, PAL_OBST),
         "#define PANO_X0 (%d)" % make_art.PANO_X0]
    stats = []

    # ---- BG4: the garden, a stage panorama (stage x PANO_X0.., the whole height) ---------------------------------
    f, w, hh = make_art.PANORAMAS["garden"]
    img = rsasset.load(os.path.join(a.art, f))
    r = rsasset.convert_bg(cells8(img, 0, 0, w, hh), 1, pal_base=PAL_GARDEN, tile_base=0)
    assert len(r.palettes) == 1
    c.append(rsasset.c_bytes("gm_garden_tiles", rsasset.tiles_bytes(r.tiles)))
    c.append("const int gm_garden_tile_count = %d;" % len(r.tiles))
    c.append(arr("gm_garden_map", [m[0] for m in r.metas]))
    c.append(arr("gm_garden_pal", rsasset.palette16(r.palettes[0])))
    h.append("#define PANO_W %d\n#define PANO_H %d" % (w // 8, hh // 8))
    h.append("extern const uint8_t gm_garden_tiles[];\nextern const int gm_garden_tile_count;")
    h.append("extern const uint16_t gm_garden_map[PANO_W * PANO_H];\nextern const uint16_t gm_garden_pal[16];")
    assert len(r.tiles) <= VR_OBJ - VR_BG4, "the garden's tiles reach the sprites'"
    stats.append("garden %d" % len(r.tiles))

    # ---- BG3: the obstacles, 16x16 each (OB_ROCK.. order: rock, bush, pot, mushroom), four map entries each -------
    f, w, hh = make_art.OBSTACLES
    img = rsasset.load(os.path.join(a.art, f))
    cells = [rsasset.cell(img, k * 16, 0, 16, 16) for k in range(w // 16)]
    r = rsasset.convert_bg(cells, 1, pal_base=PAL_OBST, tile_base=0)
    assert len(r.palettes) == 1
    c.append(rsasset.c_bytes("gm_obst_tiles", rsasset.tiles_bytes(r.tiles)))
    c.append("const int gm_obst_tile_count = %d;" % len(r.tiles))
    c.append(arr("gm_obst_map", [e for m in r.metas for e in m]))
    c.append(arr("gm_obst_pal", rsasset.palette16(r.palettes[0])))
    h.append("extern const uint8_t gm_obst_tiles[];\nextern const int gm_obst_tile_count;")
    h.append("extern const uint16_t gm_obst_map[%d];\nextern const uint16_t gm_obst_pal[16];" % (len(cells) * 4))
    stats.append("obstacles %d" % len(r.tiles))

    # ---- sprites ----------------------------------------------------------------------------------------------------
    sheet = rsasset.load(os.path.join(a.art, "sprites.png"))
    tiles, rows, names, pals = [], [], [], [0] * 128
    body_pals = []
    idx = 0
    for g in ("hero", "props", "small"):
        ents = [e for e in make_art.SPRITES if e[6] == g]
        frames = []
        for name, x, y, w, hh, n, _g in ents:
            frames += [rsasset.cell(sheet, x + i * w, y, w, hh) for i in range(n)]
        cols = set()
        for fr in frames:
            cols |= rsasset.colors_of(fr)
        assert len(cols) <= 15, (g, len(cols))
        ro = rsasset.convert_obj(frames)
        p16 = rsasset.palette16(ro.palette)
        pals[OBJ_PAL[g] * 16:OBJ_PAL[g] * 16 + 16] = p16
        if g == "hero":
            rgb = [rsasset.rgb888(v) for v in p16[1:]]
            sw = hs.player_palettes(rgb, *P2_HUE)               # [P1, P2, P3, P4]
            sw[3] = orange(rgb, *P2_HUE[:2])
            for p, slot in ((1, 1), (2, 4), (3, 5)):
                pals[slot * 16:slot * 16 + 16] = [0] + [rsasset.to555(v) for v in sw[p]]
            body_pals = [p16] + [[0] + [rsasset.to555(v) for v in sw[p]] for p in (1, 2, 3)]
        k = 0
        for name, x, y, w, hh, n, _g in ents:
            names.append("SPR_%s = %d" % (name.upper(), idx))
            for f_ in range(n):
                first, fw, fh = ro.frames[k]
                rows.append("{%d, %d, %d, %d}" % (len(tiles) + first, fw, fh, OBJ_PAL[g]))
                k += 1
                idx += 1
        tiles += ro.tiles
    assert len(tiles) <= KIT_OBJ_TILE, "the sprites overlap the kit's tiles: raise KIT_OBJ_TILE"
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(names), idx))
    h.append("typedef struct gm_sprite_def { uint16_t tile; uint8_t w, h, pal; } gm_sprite_def;")
    h.append("extern const gm_sprite_def gm_spr[SPR_COUNT];")
    h.append("extern const uint8_t gm_obj_tiles[];\nextern const int gm_obj_tile_count;\n"
             "extern const uint16_t gm_obj_pals[128];\nextern const uint16_t gm_body_pals[64];")
    c.append("const gm_sprite_def gm_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("gm_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gm_obj_tile_count = %d;" % len(tiles))
    c.append(rsasset.c_u16("gm_obj_pals", pals))
    c.append(rsasset.c_u16("gm_body_pals", [v for p in body_pals for v in p]))
    stats.append("OBJ %d" % len(tiles))

    # ---- the asset pack: the music ------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        data = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, data, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(data)))
    c.append("const rs_asset_entry gm_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry gm_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: tiles %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
