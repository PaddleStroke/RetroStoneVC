#!/usr/bin/env python3
"""Lemur Leap asset build: the code-drawn sheets (make_art.py: indexed PNGs, one fixed palette each) -> the sprites' tiles
and table, the side panels', clouds' and stars' tiles and maps, the palettes; the music (make_music.py) ->
build/gen/lemurleap/assets.c + assets.h.

    build_assets.py --out build/gen/lemurleap [--art games/lemurleap/art] [--tileset IGNORED]

VRAM (tiles, absolute; docs/spec.md "Video memory": the guideline is 64 KiB = 2048 tiles with the maps):
    0..296      BG1 the house kit (font, panel font, 2x cache, panel frame)
    297..312    BG1 the HUD's own tiles
    313..568    BG1 the glyph pool of the translated text (docs/i18n.md)
    569..888    BG1 the title's logo
    896..       BG2 the side panels (the beanstalk)
    VR_CLOUDS   BG4 the far clouds;  VR_STARS  BG3 the stars
    VR_OBJ      the sprites (the lemur, the hats, the leaves, the items, the pests, the effects), then the kit's
MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/lemurleap/LICENSE.
"""
import argparse
import glob
import json
import os
import subprocess
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
import rsasset  # noqa: E402
import make_art  # noqa: E402

VR_BG1, UI_TILE, EXT_TILE, EXT_COUNT, LOGO_TILE = 0, 297, 313, 256, 569
VR_PANEL = 896
PAL_UI, PAL_STALK, PAL_CLOUDS, PAL_STARS, PAL_LOGO = 0, 1, 2, 3, 5
OBJ_HERO, OBJ_HATS, OBJ_PLATS, OBJ_KIT, OBJ_ITEMS, OBJ_PESTS, OBJ_FX = 0, 1, 2, 3, 4, 5, 6


def indices(im, x, y, w, h):
    px = im.load()
    return [[px[x + i, y + j] for i in range(w)] for j in range(h)]


def split8(c):
    h, w = len(c), len(c[0])
    return [[c[ty + y][tx + x] for y in range(8) for x in range(8)] for ty in range(0, h, 8) for tx in range(0, w, 8)]


def pal555(rgbs):
    return [0] + [rsasset.to555(tuple(c)) for c in rgbs]


def hflip(t):
    return [t[y * 8 + 7 - x] for y in range(8) for x in range(8)]


def vflip(t):
    return [t[(7 - y) * 8 + x] for y in range(8) for x in range(8)]


def bg_tiles(grid_tiles, blank=True):
    """8x8 tiles (index lists) -> unique tiles (flips found) and one map entry each (tile, hflip, vflip)"""
    tiles, index, entries = [], {}, []
    if blank:
        tiles.append([0] * 64)
        index[tuple([0] * 64)] = (0, 0, 0)
    for t in grid_tiles:
        hit = index.get(tuple(t))
        if hit is None:
            for hf, vf, f in ((1, 0, hflip), (0, 1, vflip), (1, 1, lambda x: vflip(hflip(x)))):
                k = tuple(f(t))
                if k in index:
                    b = index[k]
                    hit = (b[0], b[1] ^ hf, b[2] ^ vf)
                    break
        if hit is None:
            tiles.append(t)
            hit = (len(tiles) - 1, 0, 0)
            index[tuple(t)] = hit
        entries.append(hit)
    return tiles, entries


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "palettes.json")):
        make_art.write_all(a.art)
    meta = json.load(open(os.path.join(a.art, "palettes.json")))
    lay, pals = meta["layouts"], meta["palettes"]
    c = ["/* Generated by games/lemurleap/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/lemurleap/tools/build_assets.py. Do not edit. */",
         "#ifndef LL_ASSETS_H\n#define LL_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n"]
    stats = []

    # ---- BG: the panels, the clouds, the stars -------------------------------------------------------------------------
    pim = Image.open(os.path.join(a.art, "panel.png"))
    pw, ph = pim.size
    ptiles, pent = bg_tiles(split8(indices(pim, 0, 0, pw, ph)), blank=True)
    vr_clouds = VR_PANEL + len(ptiles)
    cim = Image.open(os.path.join(a.art, "clouds.png"))
    ctiles, cent = bg_tiles(split8(indices(cim, 0, 0, 256, 256)))
    vr_stars = vr_clouds + len(ctiles)
    sim = Image.open(os.path.join(a.art, "stars.png"))
    stiles, sent = bg_tiles(split8(indices(sim, 0, 0, 256, 256)))
    vr_obj = vr_stars + len(stiles)
    vr_obj = (vr_obj + 7) // 8 * 8
    for name, tiles, ent, cols in (("panel", ptiles, pent, pw // 8), ("clouds", ctiles, cent, 32), ("stars", stiles, sent, 32)):
        c.append(rsasset.c_bytes("ll_%s_tiles" % name, rsasset.tiles_bytes(tiles)))
        c.append("const uint16_t ll_%s_map[%d] = {%s};" % (name, len(ent), ", ".join(
            "0x%04x" % (t | (hf << 14) | (vf << 15)) for t, hf, vf in ent)))
        h.append("#define %s_TILES %d\nextern const uint8_t ll_%s_tiles[];\nextern const uint16_t ll_%s_map[%d];" %
                 (name.upper(), len(tiles), name, name, len(ent)))
        stats.append("%s %d" % (name, len(tiles)))
    h.append("#define PANEL_COLS %d\n#define PANEL_ROWS %d" % (pw // 8, ph // 8))

    # ---- sprites ---------------------------------------------------------------------------------------------------------
    tiles, rows, names = [], [], []
    idx = 0
    for sheet, pal in (("hero", OBJ_HERO), ("hats", OBJ_HATS), ("plats", OBJ_PLATS), ("items", OBJ_ITEMS),
                       ("pests", OBJ_PESTS), ("fx", OBJ_FX)):
        im = Image.open(os.path.join(a.art, sheet + ".png"))
        for name, x, y, w, hh, n in lay[sheet]:
            prefix = "HAT" if sheet == "hats" else "HERO" if sheet == "hero" else "SPR"
            names.append("%s_%s = %d" % (prefix, name.upper(), idx))
            for f in range(n):
                rows.append("{%d, %d, %d, %d}" % (len(tiles), w, hh, pal))
                tiles += split8(indices(im, x + f * w, y, w, hh))
                idx += 1
    kit_tile = len(tiles)
    assert vr_obj + kit_tile + 118 <= 4096
    h.append("#define VR_BG1 %d\n#define UI_TILE %d\n#define EXT_TILE %d\n#define EXT_COUNT %d\n#define LOGO_TILE %d" %
             (VR_BG1, UI_TILE, EXT_TILE, EXT_COUNT, LOGO_TILE))
    h.append("#define VR_PANEL %d\n#define VR_CLOUDS %d\n#define VR_STARS %d\n#define VR_OBJ %d\n#define KIT_OBJ_TILE %d" %
             (VR_PANEL, vr_clouds, vr_stars, vr_obj, kit_tile))
    for k, v in (("PAL_UI", PAL_UI), ("PAL_STALK", PAL_STALK), ("PAL_CLOUDS", PAL_CLOUDS), ("PAL_STARS", PAL_STARS),
                 ("PAL_LOGO", PAL_LOGO), ("OBJ_HERO", OBJ_HERO), ("OBJ_HATS", OBJ_HATS), ("OBJ_PLATS", OBJ_PLATS),
                 ("OBJ_KIT", OBJ_KIT), ("OBJ_ITEMS", OBJ_ITEMS), ("OBJ_PESTS", OBJ_PESTS), ("OBJ_FX", OBJ_FX)):
        h.append("#define %s %d" % (k, v))
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(names), idx))
    h.append("typedef struct ll_sprite_def { uint16_t tile; uint8_t w, h, pal; } ll_sprite_def;")
    h.append("extern const ll_sprite_def ll_spr[SPR_COUNT];")
    h.append("extern const uint8_t ll_obj_tiles[];\nextern const int ll_obj_tile_count;")
    c.append("const ll_sprite_def ll_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("ll_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int ll_obj_tile_count = %d;" % len(tiles))
    stats.append("OBJ %d (kit at %d)" % (len(tiles), kit_tile))
    # where a hat sits on each frame of the lemur (the head's top centre in the 24x24 frame)
    fr = meta["hero_frames"]
    c.append("const int8_t ll_hero_head[%d][2] = {%s};" % (len(fr), ", ".join(
        "{%d, %d}" % tuple(meta["anchors"][n]) for n in fr)))
    h.append("#define HERO_FRAMES %d\nextern const int8_t ll_hero_head[HERO_FRAMES][2];" % len(fr))

    # ---- palettes ---------------------------------------------------------------------------------------------------------
    for key in ("hats", "plats", "items", "pests", "fx", "stars"):
        c.append(rsasset.c_u16("ll_pal_" + key, pal555(pals[key])))
        h.append("extern const uint16_t ll_pal_%s[16];" % key)
    furs = meta["furs"]
    c.append("const uint16_t ll_pal_fur[%d][16] = {" % len(furs))
    for f in furs:
        c.append("{" + ", ".join("0x%04x" % v for v in pal555(pals["fur_" + f])) + "},")
    c.append("};")
    h.append("extern const uint16_t ll_pal_fur[%d][16];" % len(furs))
    for key in ("stalk", "clouds"):
        c.append("const uint16_t ll_pal_%s[4][16] = {" % key)
        for z in ("garden", "clouds", "sky", "space"):
            c.append("{" + ", ".join("0x%04x" % v for v in pal555(pals["%s_%s" % (key, z)])) + "},")
        c.append("};")
        h.append("extern const uint16_t ll_pal_%s[4][16];" % key)

    # ---- the asset pack: the music --------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        d = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, d, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(d)))
    c.append("const rs_asset_entry ll_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry ll_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
