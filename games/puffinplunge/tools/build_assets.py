#!/usr/bin/env python3
"""Puffin Plunge asset build: the code-drawn sheets (make_art.py: indexed PNGs, one fixed palette each) -> the sprites'
tiles, the four zones' terrain and back-wall tiles, the palettes; the music (make_music.py) and the chunks
(levels/chunks.txt) -> the asset pack. Writes build/gen/puffinplunge/assets.c + assets.h.

    build_assets.py --out build/gen/puffinplunge [--art games/puffinplunge/art] [--tileset IGNORED]

VRAM (tiles, absolute; docs/spec.md "Video memory": the guideline is 64 KiB = 2048 tiles with the maps):
    0..296      BG1 the house kit (font, panel font, 2x cache, panel frame)
    297..319    BG1 the HUD's own tiles
    320..575    BG1 the glyph pool of the translated text (docs/i18n.md: a Japanese title takes 256)
    576..895    BG1 the title's logo
    1024..      BG2 the shaft (two zones at a time, a slot each: the terrain, rock quarters, crystals, doors, the floors, the side panels'
                decorations) and BG3 the back wall, after it (one zone's tiles at a time, loaded with the level)
    2048..      the sprites: the puffin, the critters, the walrus, the items, the effects, then the kit's
MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/puffinplunge/LICENSE.
"""
import argparse
import glob
import json
import os
import subprocess
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
import rsasset  # noqa: E402
import make_art  # noqa: E402

VR_BG1, EXT_TILE, EXT_COUNT, LOGO_TILE, UI_TILE, VR_SHAFT, VR_OBJ = 0, 320, 256, 576, 297, 1024, 2048
PAL_UI, PAL_ROCK, PAL_SIDE, PAL_BACK, PAL_ROCK2, PAL_LOGO, PAL_SIDE2, PAL_BACK2 = 0, 1, 2, 3, 4, 5, 6, 7
OBJ_HERO, OBJ_CRIT, OBJ_ITEMS, OBJ_KIT, OBJ_FX, OBJ_BOSS, OBJ_FLASH, OBJ_CRIT2 = 0, 1, 2, 3, 4, 5, 6, 7


def indices(im, x, y, w, h):
    px = im.load()
    return [[px[x + i, y + j] for i in range(w)] for j in range(h)]


def split8(c):
    h, w = len(c), len(c[0])
    out = []
    for ty in range(0, h, 8):
        for tx in range(0, w, 8):
            out.append([c[ty + y][tx + x] for y in range(8) for x in range(8)])
    return out


def pal555(rgbs):
    rgbs = list(rgbs)[:15] + [(0, 0, 0)] * (15 - len(rgbs))
    return [0] + [rsasset.to555(tuple(c)) for c in rgbs]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "palettes.json")):
        make_art.write_all(a.art)
    meta = json.load(open(os.path.join(a.art, "palettes.json")))
    lay, pals = meta["layouts"], meta["palettes"]
    c = ["/* Generated by games/puffinplunge/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/puffinplunge/tools/build_assets.py. Do not edit. */",
         "#ifndef PP_ASSETS_H\n#define PP_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n"]
    for k, v in (("VR_BG1", VR_BG1), ("EXT_TILE", EXT_TILE), ("EXT_COUNT", EXT_COUNT), ("LOGO_TILE", LOGO_TILE),
                 ("UI_TILE", UI_TILE), ("VR_SHAFT", VR_SHAFT), ("VR_OBJ", VR_OBJ), ("PAL_UI", PAL_UI),
                 ("PAL_ROCK", PAL_ROCK), ("PAL_SIDE", PAL_SIDE), ("PAL_BACK", PAL_BACK), ("PAL_LOGO", PAL_LOGO),
                 ("PAL_ROCK2", PAL_ROCK2), ("PAL_SIDE2", PAL_SIDE2), ("PAL_BACK2", PAL_BACK2), ("OBJ_CRIT2", OBJ_CRIT2),
                 ("OBJ_HERO", OBJ_HERO), ("OBJ_CRIT", OBJ_CRIT), ("OBJ_ITEMS", OBJ_ITEMS), ("OBJ_KIT", OBJ_KIT),
                 ("OBJ_FX", OBJ_FX), ("OBJ_BOSS", OBJ_BOSS), ("OBJ_FLASH", OBJ_FLASH)):
        h.append("#define %s %d" % (k, v))
    stats = []

    # ---- the sprites --------------------------------------------------------------------------------------------
    tiles, rows, names = [], [], []
    idx = 0
    for sheet, pal in (("hero", OBJ_HERO), ("critters", OBJ_CRIT), ("walrus", OBJ_BOSS), ("items", OBJ_ITEMS),
                       ("fx", OBJ_FX)):
        im = Image.open(os.path.join(a.art, sheet + ".png"))
        for name, x, y, w, hh, n in lay[sheet]:
            names.append("SPR_%s = %d" % (name.upper(), idx))
            for f in range(n):
                rows.append("{%d, %d, %d, %d}" % (len(tiles), w, hh, pal))
                tiles += split8(indices(im, x + f * w, y, w, hh))
                idx += 1
    kit_tile = len(tiles)
    h.append("#define KIT_OBJ_TILE %d" % kit_tile)
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(names), idx))
    h.append("typedef struct pp_sprite_def { uint16_t tile; uint8_t w, h, pal; } pp_sprite_def;")
    h.append("extern const pp_sprite_def pp_spr[SPR_COUNT];")
    h.append("extern const uint8_t pp_obj_tiles[];\nextern const int pp_obj_tile_count;")
    c.append("const pp_sprite_def pp_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("pp_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int pp_obj_tile_count = %d;" % len(tiles))
    assert VR_OBJ + kit_tile + 118 <= 4096, "the sprites' tiles overflow"
    stats.append("OBJ %d tiles (kit at %d)" % (len(tiles), kit_tile))

    # ---- the terrain and the back wall, per zone ------------------------------------------------------------------
    tnames, zt, zb = [], [], []
    for z in range(1, 5):
        im = Image.open(os.path.join(a.art, "terrain_z%d.png" % z))
        t = []
        for name, x, y, w, hh, n in lay["terrain"]:
            if z == 1:
                tnames.append("T_%s = %d" % (name.upper(), len(t)))
            t += split8(indices(im, x, y, w, hh))
        zt.append(t)
        im = Image.open(os.path.join(a.art, "back_z%d.png" % z))
        b = []
        for name, x, y, w, hh, n in lay["back"]:
            b += split8(indices(im, x, y, w, hh))
        zb.append(b)
    h.append("enum { %s, T_COUNT = %d };" % (", ".join(tnames), len(zt[0])))
    h.append("#define BACK_TILES %d" % len(zb[0]))
    h.append("extern const uint8_t pp_terrain[4][T_COUNT * 32];\nextern const uint8_t pp_back[4][BACK_TILES * 32];")
    c.append("const uint8_t pp_terrain[4][T_COUNT * 32] = {")
    for t in zt:
        c.append("{" + ", ".join("0x%02x" % v for v in rsasset.tiles_bytes(t)) + "},")
    c.append("};")
    c.append("const uint8_t pp_back[4][BACK_TILES * 32] = {")
    for t in zb:
        c.append("{" + ", ".join("0x%02x" % v for v in rsasset.tiles_bytes(t)) + "},")
    c.append("};")
    stats.append("terrain %d + back %d tiles a zone" % (len(zt[0]), len(zb[0])))

    # ---- the palettes ----------------------------------------------------------------------------------------------
    for key in ("hero", "items", "fx", "walrus"):
        c.append(rsasset.c_u16("pp_pal_" + key, pal555(pals[key])))
        h.append("extern const uint16_t pp_pal_%s[16];" % key)
    for group, fmt in (("crit", "zone%d"), ("terrain", "terrain_z%d"), ("back", "back_z%d")):
        c.append("const uint16_t pp_pal_%s[4][16] = {" % group)
        for z in range(1, 5):
            c.append("{" + ", ".join("0x%04x" % v for v in pal555(pals[fmt % z])) + "},")
        c.append("};")
        h.append("extern const uint16_t pp_pal_%s[4][16];" % group)

    # ---- the asset pack: the music, the chunks -----------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    pack.append(("levels/chunks.txt", os.path.join(GAME, "levels", "chunks.txt")))
    entries = []
    for i, (name, path) in enumerate(pack):
        d = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, d, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(d)))
    c.append("const rs_asset_entry pp_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry pp_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
