#!/usr/bin/env python3
"""Snowball Siege asset build: the code-drawn sheets (make_art.py) -> tiles, palettes, the far map and the sprites; the
terrain's palette; the music (make_music.py) -> build/gen/snowballsiege/assets.c + assets.h.

    build_assets.py --out build/gen/snowballsiege [--art games/snowballsiege/art] [--tileset IGNORED]

VRAM (tiles of 32 bytes): BG1 the UI at 0 (the kit 0..296, the logo 320..639, the glyph pool 640..767, the field's map
768..839), BG2 the snowy field at 1024 (drawn at run time: an empty tile, the shared inner tiles, then a pool of
TERRAIN_POOL tiles), BG3 the far mountains at 1536, the sprites at 1792 (the kit's after ours).

MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/snowballsiege/LICENSE.
"""
import argparse
import glob
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "games", "common", "tools"))
import rsasset  # noqa: E402
import make_art as ma  # noqa: E402

PAL_TERRAIN, PAL_FAR, PAL_LOGO = 1, 2, 5
VR_BG1, VR_BG2, VR_BG3, VR_OBJ = 0, 1024, 1536, 1792
TERRAIN_POOL = 400                       # BG2 tiles for the field's edges (shared, deduplicated: draw.c)
FAR_Y = 72                               # the far panorama's top, screen y
TEAM_OBJ = [0, 1, 4, 5]                  # the teams' sprite palettes: the house rule for players 1-4
PROPS_OBJ, SCENE_OBJ = 2, 6


def cells8(img, w, h):
    return [rsasset.cell(img, x * 8, y * 8, 8, 8) for y in range(h // 8) for x in range(w // 8)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "critters.png")):
        ma.write_all(a.art)
    c = ["/* Generated by games/snowballsiege/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/snowballsiege/tools/build_assets.py. Do not edit. */",
         "#ifndef GM_ASSETS_H\n#define GM_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n",
         "#define VR_BG1 %d\n#define VR_BG2 %d\n#define VR_BG3 %d\n#define VR_OBJ %d" % (VR_BG1, VR_BG2, VR_BG3, VR_OBJ),
         "#define PAL_TERRAIN %d\n#define PAL_FAR %d\n#define PAL_LOGO %d" % (PAL_TERRAIN, PAL_FAR, PAL_LOGO),
         "#define TERRAIN_POOL %d\n#define FAR_Y %d" % (TERRAIN_POOL, FAR_Y)]
    stats = []

    # ---- BG3: the far panorama (256 x 128, repeating) ------------------------------------------------------------------
    img = rsasset.load(os.path.join(a.art, "tiles/far.png"))
    r = rsasset.convert_bg(cells8(img, 256, 128), 1, pal_base=PAL_FAR, tile_base=0)
    c.append(rsasset.c_bytes("gm_far_tiles", rsasset.tiles_bytes(r.tiles)))
    c.append("const int gm_far_tile_count = %d;" % len(r.tiles))
    c.append(rsasset.c_u16("gm_far_map", [m[0] for m in r.metas]))
    c.append(rsasset.c_u16("gm_far_pal", rsasset.palette16(r.palettes[0])))
    h.append("#define FAR_W 32\n#define FAR_H 16")
    h.append("extern const uint8_t gm_far_tiles[];\nextern const int gm_far_tile_count;")
    h.append("extern const uint16_t gm_far_map[FAR_W * FAR_H];\nextern const uint16_t gm_far_pal[16];")
    stats.append("BG3 %d" % len(r.tiles))
    assert VR_BG3 + len(r.tiles) <= VR_OBJ, "the far tiles overlap the sprites"

    # ---- the terrain's palette (BG2 is drawn at run time) ----------------------------------------------------------------
    c.append(rsasset.c_u16("gm_terrain_pal", rsasset.palette16([rsasset.to555(x) for x in ma.TERRAIN])))
    h.append("extern const uint16_t gm_terrain_pal[16];")

    # ---- sprites: the four teams (a palette each), the props, the scenery ---------------------------------------------
    crit = rsasset.load(os.path.join(a.art, "critters.png"))
    tiles, rows, names = [], [], []
    pals = [[0] * 16 for _ in range(8)]
    for si, sp in enumerate(ma.SPECIES):
        pal = ma.team_palette(sp)
        frames = [rsasset.cell(crit, pi * 16, si * 16, 16, 16) for pi in range(len(ma.POSES))]
        ro = rsasset.convert_obj(frames, palette=[rsasset.to555(x) for x in pal])
        pals[TEAM_OBJ[si]] = rsasset.palette16([rsasset.to555(x) for x in pal])
        for k, pose in enumerate(ma.POSES):
            first, fw, fh = ro.frames[k]
            names.append("SPR_%s_%s = %d" % (sp.upper(), pose.upper(), len(rows)))
            rows.append("{%d, %d, %d, %d}" % (len(tiles) + first, fw, fh, TEAM_OBJ[si]))
        tiles += ro.tiles
    for group, sprites, pal, objpal in (("props", ma.props(), ma.PROPS_PAL, PROPS_OBJ),
                                        ("scenery", ma.scenery(), ma.SCENE_PAL, SCENE_OBJ)):
        sheet = rsasset.load(os.path.join(a.art, group + ".png"))
        pos, _ = ma.pack(sprites)
        order = sorted(pos)
        frames = [rsasset.cell(sheet, *pos[n]) for n in order]
        ro = rsasset.convert_obj(frames, palette=[rsasset.to555(x) for x in pal])
        pals[objpal] = rsasset.palette16([rsasset.to555(x) for x in pal])
        for k, n in enumerate(order):
            first, fw, fh = ro.frames[k]
            names.append("SPR_%s = %d" % (n.upper(), len(rows)))
            rows.append("{%d, %d, %d, %d}" % (len(tiles) + first, fw, fh, objpal))
        tiles += ro.tiles
    kit_tile = (len(tiles) + 7) // 8 * 8
    h.append("#define KIT_OBJ_TILE %d\n#define CRIT_POSES %d" % (kit_tile, len(ma.POSES)))
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(names), len(rows)))
    h.append("typedef struct gm_sprite_def { uint16_t tile; uint8_t w, h, pal; } gm_sprite_def;")
    h.append("extern const gm_sprite_def gm_spr[SPR_COUNT];")
    h.append("extern const uint8_t gm_obj_tiles[];\nextern const int gm_obj_tile_count;\n"
             "extern const uint16_t gm_obj_pals[128];")
    c.append("const gm_sprite_def gm_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("gm_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gm_obj_tile_count = %d;" % len(tiles))
    c.append(rsasset.c_u16("gm_obj_pals", [v for p in pals for v in p]))
    stats.append("OBJ %d" % len(tiles))

    # ---- the asset pack: the music ------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        data = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, data, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(data)))
    c.append("const rs_asset_entry gm_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry gm_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: tiles %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
