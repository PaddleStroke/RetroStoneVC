#!/usr/bin/env python3
"""Kitty Kibble asset build: the code-drawn sheets (make_art.py) -> tiles, palettes, maps and sprites; the music
(make_music.py) -> build/gen/kittykibble/assets.c + assets.h.

    build_assets.py --out build/gen/kittykibble [--art games/kittykibble/art] [--tileset IGNORED]

MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/kittykibble/LICENSE.
"""
import argparse
import glob
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "games", "common", "tools"))
import rsasset  # noqa: E402
import make_art  # noqa: E402

# BG palettes: 0 the UI (the kit), 1 the walls (each room its own), 2 the kibble, gate and dock, 3-6 the room around
# the maze (each room its own), 7 the logo (the kit)
PAL_WALL, PAL_ITEMS, PAL_ROOM, PAL_LOGO = 1, 2, 3, 7
ROOM_PALS = 4
# OBJ palettes: 0 the kitten (P1, ginger), 1 P2 (silver), 2 the props, 3 the kit, 4 P3 (snow white), 5 P4 (chocolate),
# 6 the vacuums, 7 the scared vacuums' flash
OBJ_PAL = {"hero": 0, "props": 2, "vac": 6}
PLAYER_SLOTS = {1: 1, 2: 4, 3: 5}
# BG1 the UI (the kit: 0..767 with the glyph pool), BG2 the maze (walls, kibble), BG3 the room, the sprites
VR_BG1, VR_BG2, VR_BG3, VR_OBJ = 0, 1024, 1280, 2048
KIT_OBJ_TILE = 256                                        # the kit's sprites (house_ui.h HU_OBJ_TILES) after ours
ROOM_TILES_MAX = 720                                      # each room's tiles at VR_BG3 (VRAM: docs/spec.md)


def cells8(img, x0, y0, w, h):
    return [rsasset.cell(img, x0 + x * 8, y0 + y * 8, 8, 8) for y in range(h // 8) for x in range(w // 8)]


def arr(name, data, static=False):
    return "%sconst uint16_t %s[%d] = {%s};" % ("static " if static else "", name, len(data),
                                               ", ".join("0x%04x" % v for v in data))


def pal16(colours):
    return [0] + [rsasset.to555(c) for c in colours] + [0] * (15 - len(colours))


def swap(p16, frm, to):
    """p16 with the colours frm replaced by to (the same order)."""
    m = {rsasset.to555(a): rsasset.to555(b) for a, b in zip(frm, to)}
    return [m.get(v, v) if i else v for i, v in enumerate(p16)]


def indexed(img, x0, y0, colours):
    """An 8x8 cell of img as palette indices (1.. = colours, 0 = see-through)."""
    c = rsasset.cell(img, x0, y0, 8, 8)
    lut = {rsasset.to555(v): i + 1 for i, v in enumerate(colours)}
    return [0 if v is None else lut[v] for row in c for v in row]


def fit_palettes(cells, n, name):
    """Merge the two closest colours of the picture (the rarer into the commoner) until its tiles pack into n
    palettes of 15 (rsasset's clustering would recolour whole tiles): returns the cells."""
    merged = 0
    while rsasset.pack_palettes([rsasset.colors_of(c) for c in cells], n) is None:
        counts = {}
        for c in cells:
            for row in c:
                for v in row:
                    if v is not None:
                        counts[v] = counts.get(v, 0) + 1
        cols = sorted(counts)
        best = None
        for i, a in enumerate(cols):
            for b in cols[i + 1:]:
                d = rsasset.dist2(rsasset.rgb888(a), rsasset.rgb888(b))
                if best is None or d < best[0]:
                    best = (d, a, b)
        _d, a, b = best
        keep, drop = (a, b) if counts[a] >= counts[b] else (b, a)
        cells = [[[keep if v == drop else v for v in row] for row in c] for c in cells]
        merged += 1
    if merged:
        print("build_assets: %s: %d close colours merged to fit %d palettes" % (name, merged, n))
    return cells


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "sprites.png")):
        make_art.write_all(a.art)
    nr = len(make_art.ROOMS)
    c = ["/* Generated by games/kittykibble/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/kittykibble/tools/build_assets.py. Do not edit. */",
         "#ifndef GM_ASSETS_H\n#define GM_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n",
         "#define VR_BG1 %d\n#define VR_BG2 %d\n#define VR_BG3 %d\n#define VR_OBJ %d\n#define KIT_OBJ_TILE %d" %
         (VR_BG1, VR_BG2, VR_BG3, VR_OBJ, KIT_OBJ_TILE),
         "#define PAL_WALL %d\n#define PAL_ITEMS %d\n#define PAL_ROOM %d\n#define PAL_LOGO %d" %
         (PAL_WALL, PAL_ITEMS, PAL_ROOM, PAL_LOGO),
         "#define PANO_X0 (%d)\n#define PANO_W %d\n#define PANO_H %d" %
         (make_art.PANO_X0, make_art.PANO_W // 8, make_art.PANO_H // 8)]
    stats = []

    # ---- BG2: the walls (47 shapes a room), the items (kibble x2, the gate, the dock's floor) -------------------
    walls = rsasset.load(os.path.join(a.art, "tiles", "walls.png"))
    nb = len(make_art.BLOB)
    wt, wp = [], []
    for r, room in enumerate(make_art.ROOMS):
        cols = make_art.WALLS[room]
        wt += [indexed(walls, i * 8, r * 8, cols) for i in range(nb)]
        wp += pal16(cols)
    lut = [make_art.BLOB.index(make_art.canon(m)) for m in range(256)]
    c.append(rsasset.c_bytes("gm_wall_tiles", rsasset.tiles_bytes(wt)))
    c.append(arr("gm_wall_pals", wp))
    c.append("const uint8_t gm_wall_lut[256] = {%s};" % ", ".join(str(v) for v in lut))
    items = rsasset.load(os.path.join(a.art, "tiles", "items.png"))
    it = [indexed(items, i * 8, 0, make_art.ITEM_COLOURS) for i in range(7)]
    c.append(rsasset.c_bytes("gm_item_tiles", rsasset.tiles_bytes(it)))
    c.append(arr("gm_item_pal", pal16(make_art.ITEM_COLOURS)))
    h.append("#define WALL_SHAPES %d\n#define WALL_TILE0 1\n#define ITEM_TILE (WALL_TILE0 + WALL_SHAPES)\n"
             "enum { TILE_KIBBLE = ITEM_TILE, TILE_KIBBLE2, TILE_GATE, TILE_DOCK, TILE_DOOR };\n#define ITEM_TILES 7" % nb)
    h.append("extern const uint8_t gm_wall_tiles[];\nextern const uint16_t gm_wall_pals[%d * 16];\n"
             "extern const uint8_t gm_wall_lut[256];\nextern const uint8_t gm_item_tiles[];\n"
             "extern const uint16_t gm_item_pal[16];" % nr)
    h.append("enum { NB_N = 1, NB_NE = 2, NB_E = 4, NB_SE = 8, NB_S = 16, NB_SW = 32, NB_W = 64, NB_NW = 128 };")
    stats.append("walls %d x %d" % (nb, nr))

    # ---- BG3: each room around the maze (two palettes) ------------------------------------------------------------
    names_t, names_n, names_m, pals = [], [], [], []
    for r, room in enumerate(make_art.ROOMS):
        img = rsasset.load(os.path.join(a.art, "tiles", "%s.png" % room))
        cells = fit_palettes(cells8(img, 0, 0, make_art.PANO_W, make_art.PANO_H), ROOM_PALS, room)
        res = rsasset.convert_bg(cells, ROOM_PALS, pal_base=PAL_ROOM, tile_base=0)
        assert len(res.tiles) <= ROOM_TILES_MAX, "room %s: %d tiles" % (room, len(res.tiles))
        c.append(rsasset.c_bytes("room_tiles_%d" % r, rsasset.tiles_bytes(res.tiles), static=True))
        c.append(arr("room_map_%d" % r, [m[0] for m in res.metas], static=True))
        p = []
        for k in range(ROOM_PALS):
            p += rsasset.palette16(res.palettes[k]) if k < len(res.palettes) else [0] * 16
        pals += p
        names_t.append("room_tiles_%d" % r)
        names_n.append(str(len(res.tiles)))
        names_m.append("room_map_%d" % r)
        stats.append("%s %d" % (room, len(res.tiles)))
    c.append("const uint8_t *const gm_room_tiles[%d] = {%s};" % (nr, ", ".join(names_t)))
    c.append("const int gm_room_tile_count[%d] = {%s};" % (nr, ", ".join(names_n)))
    c.append("const uint16_t *const gm_room_map[%d] = {%s};" % (nr, ", ".join(names_m)))
    c.append(arr("gm_room_pals", pals))
    h.append("extern const uint8_t *const gm_room_tiles[%d];\nextern const int gm_room_tile_count[%d];\n"
             "extern const uint16_t *const gm_room_map[%d];\nextern const uint16_t gm_room_pals[%d * 64];" %
             (nr, nr, nr, nr))

    # ---- sprites ----------------------------------------------------------------------------------------------------
    sheet = rsasset.load(os.path.join(a.art, "sprites.png"))
    tiles, rows, names, pals = [], [], [], [0] * 128
    idx = 0
    for g in ("hero", "props", "vac"):
        ents = [e for e in make_art.SPRITES if e[6] == g]
        frames = []
        for name, x, y, w, hh, n, _g in ents:
            frames += [rsasset.cell(sheet, x + i * w, y, w, hh) for i in range(n)]
        cols = set()
        for fr in frames:
            cols |= rsasset.colors_of(fr)
        assert len(cols) <= 15, (g, len(cols), sorted(rsasset.rgb888(v) for v in cols))
        ro = rsasset.convert_obj(frames)
        p16 = rsasset.palette16(ro.palette)
        pals[OBJ_PAL[g] * 16:OBJ_PAL[g] * 16 + 16] = p16
        if g == "hero":                     # players 2-4: the fur and the collar recoloured (silver, white, chocolate)
            for p, slot in PLAYER_SLOTS.items():
                pals[slot * 16:slot * 16 + 16] = swap(p16, make_art.FUR + [make_art.COLLAR],
                                                      make_art.FUR_P[p] + [make_art.COLLAR_P[p]])
        if g == "vac":                      # the flash: the scared blue turns white, the white eyes red
            pals[7 * 16:8 * 16] = swap(p16, make_art.BLUE + [make_art.WHITE],
                                       make_art.FLASH + [make_art.VCOL["dash"][0]])
        k = 0
        for name, x, y, w, hh, n, _g in ents:
            names.append("SPR_%s = %d" % (name.upper(), idx))
            for f in range(n):
                first, fw, fh = ro.frames[k]
                rows.append("{%d, %d, %d, %d}" % (len(tiles) + first, fw, fh, OBJ_PAL[g]))
                k += 1
                idx += 1
        tiles += ro.tiles
    assert len(tiles) <= KIT_OBJ_TILE, "the sprites overlap the kit's tiles: raise KIT_OBJ_TILE"
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(names), idx))
    h.append("typedef struct gm_sprite_def { uint16_t tile; uint8_t w, h, pal; } gm_sprite_def;")
    h.append("extern const gm_sprite_def gm_spr[SPR_COUNT];")
    h.append("extern const uint8_t gm_obj_tiles[];\nextern const int gm_obj_tile_count;\n"
             "extern const uint16_t gm_obj_pals[128];")
    c.append("const gm_sprite_def gm_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("gm_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gm_obj_tile_count = %d;" % len(tiles))
    c.append(rsasset.c_u16("gm_obj_pals", pals))
    stats.append("OBJ %d" % len(tiles))

    # ---- the asset pack: the music ------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        data = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, data, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(data)))
    c.append("const rs_asset_entry gm_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry gm_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: tiles %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
