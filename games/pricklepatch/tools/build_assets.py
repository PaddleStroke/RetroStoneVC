#!/usr/bin/env python3
"""Prickle Patch asset build: the code-drawn sheets (make_art.py: indexed PNGs, one fixed palette each) -> the soft
layer's pixels (8 bits per pixel, read by src/soft.c), the sprites' and the garden's tiles, the palettes; the music
(make_music.py) -> build/gen/pricklepatch/assets.c + assets.h.

    build_assets.py --out build/gen/pricklepatch [--art games/pricklepatch/art] [--tileset IGNORED]

VRAM (tiles, absolute; docs/spec.md "Video memory": the guideline is 64 KiB = 2048 tiles with the maps):
    0..296      BG1 the house kit (font, panel font, 2x cache, panel frame)
    297..316    BG1 the HUD's own tiles (the XP and boss bars)
    317..572    BG1 the glyph pool of the translated text (docs/i18n.md; 256 tiles: a Japanese title takes them)
    573..892    BG1 the title's logo, and while a run is under way the soft layer's first tiles (BG2's base is 573:
                the logo is drawn again when the title comes back)
    573..1595   BG2 the soft layer's pool (its tile 0 stays clear): 768 tiles at 320 x 240, 1023 on a wider or a
                taller screen (a phone: more of the garden, more pests on it)
    1600..      BG4 the garden (grass, flowers, dirt, cabbages, the XP gems)
    3072..      the sprites: the gardener, the tools, the items, the see-through effects, the number pops, then the kit's
At 320 x 240 (the console) everything, the pool full and the glyph pool too, stays within the 64 KiB guideline. A phone
held upright needs maps of 64 rows for BG2 and BG4 (8 KiB more) and gets the bigger pool: there a full pool goes past the
guideline by a few KiB (a guideline: the phone has no such limit; DESIGN.md "The soft sprite layer").
MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/pricklepatch/LICENSE.
"""
import argparse
import glob
import json
import os
import subprocess
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
import rsasset  # noqa: E402
import make_art  # noqa: E402

VR_BG1, VR_SOFT, SOFT_POOL, EXT_TILE, EXT_COUNT, VR_GROUND, VR_OBJ = 0, 573, 1023, 317, 256, 1600, 3072
SOFT_POOL_CONSOLE = 768                # the pool used at 320 x 240 (the console): within the VRAM guideline
UI_TILE = 297                       # the HUD's tiles, relative to BG1's base
LOGO_TILE = 573                     # the title's logo, relative to BG1's base (the pool's first tiles)
POP_TILES = 32                      # the number pops: 16 sprites of 16x8, drawn at run time
PAL_UI, PAL_GROUND, PAL_SOFT, PAL_LOGO = 0, 1, 2, 5
OBJ_HERO, OBJ_TOOLS, OBJ_ITEMS, OBJ_KIT, OBJ_FX = 0, 1, 2, 3, 4


def indices(im, x, y, w, h):
    px = im.load()
    return [[px[x + i, y + j] for i in range(w)] for j in range(h)]


def split8(c):
    """a w x h index grid -> its 8x8 tiles, row-major, each 64 indices"""
    h, w = len(c), len(c[0])
    out = []
    for ty in range(0, h, 8):
        for tx in range(0, w, 8):
            out.append([c[ty + y][tx + x] for y in range(8) for x in range(8)])
    return out


def pal555(rgbs):
    return [0] + [rsasset.to555(c) for c in rgbs]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "palettes.json")):
        make_art.write_all(a.art)
    meta = json.load(open(os.path.join(a.art, "palettes.json")))
    lay, pals = meta["layouts"], meta["palettes"]
    c = ["/* Generated by games/pricklepatch/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/pricklepatch/tools/build_assets.py. Do not edit. */",
         "#ifndef PP_ASSETS_H\n#define PP_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n"]
    for k, v in (("VR_BG1", VR_BG1), ("VR_SOFT", VR_SOFT), ("SOFT_POOL", SOFT_POOL), ("EXT_TILE", EXT_TILE),
                 ("EXT_COUNT", EXT_COUNT), ("VR_GROUND", VR_GROUND), ("VR_OBJ", VR_OBJ), ("UI_TILE", UI_TILE),
                 ("LOGO_TILE", LOGO_TILE), ("SOFT_POOL_CONSOLE", SOFT_POOL_CONSOLE),
                 ("PAL_UI", PAL_UI), ("PAL_GROUND", PAL_GROUND), ("PAL_SOFT", PAL_SOFT), ("PAL_LOGO", PAL_LOGO),
                 ("OBJ_HERO", OBJ_HERO), ("OBJ_TOOLS", OBJ_TOOLS), ("OBJ_ITEMS", OBJ_ITEMS), ("OBJ_KIT", OBJ_KIT),
                 ("OBJ_FX", OBJ_FX)):
        h.append("#define %s %d" % (k, v))
    stats = []

    # ---- the soft layer: 8-bit pixels, frame by frame ------------------------------------------------------------
    im = Image.open(os.path.join(a.art, "soft.png"))
    data, defs, names = bytearray(), [], []
    for name, x, y, w, hh, n in lay["soft"]:
        names.append("SF_%s = %d" % (name.upper(), len(defs)))
        for f in range(n):
            g = indices(im, x + f * w, y, w, hh)
            # cropped to what it draws (fewer 8x8 cells touched: fewer tiles of the pool), its place in the frame kept
            ys = [j for j in range(hh) if any(g[j])] or [0]
            xs = [i for i in range(w) if any(g[j][i] for j in range(hh))] or [0]
            x0, x1, y0, y1 = min(xs), max(xs) + 1, min(ys), max(ys) + 1
            defs.append("{%d, %d, %d, %d, %d, %d, %d, %d}" % (len(data), x1 - x0, y1 - y0, x0, w - x1, y0, w, hh))
            for row in g[y0:y1]:
                data += bytes(row[x0:x1])
    h.append("enum { %s, SF_COUNT = %d };" % (", ".join(names), len(defs)))
    h.append("typedef struct pp_soft_def { uint32_t off; uint8_t w, h, ox, oxf, oy, fw, fh; } pp_soft_def;   /* w x h at ox, oy: the crop of its fw x fh frame (oxf: from the right, flipped) */")
    h.append("extern const pp_soft_def pp_soft[SF_COUNT];\nextern const uint8_t pp_soft_px[];")
    c.append("const pp_soft_def pp_soft[SF_COUNT] = {\n    " + ",\n    ".join(defs) + "};")
    c.append(rsasset.c_bytes("pp_soft_px", bytes(data)))
    stats.append("soft %d frames %d bytes" % (len(defs), len(data)))

    # ---- the sprites: the gardener (one of three, loaded at the same tiles), the tools, the items, the effects -----
    tiles, rows, enames = [], [], []
    idx = 0
    hero_tiles = []
    for cname in ("hedgehog", "tortoise", "hen"):
        imh = Image.open(os.path.join(a.art, "hero_%s.png" % cname))
        t = []
        for name, x, y, w, hh, n in lay["hero_" + cname]:
            for f in range(n):
                t += split8(indices(imh, x + f * w, y, w, hh))
        hero_tiles.append(t)
    hero_n = len(hero_tiles[0])
    enames.append("SPR_HERO = 0")
    for f in range(4):
        rows.append("{%d, 24, 24, %d}" % (f * 9, OBJ_HERO))
    idx = 4
    tiles = [[0] * 64 for _ in range(hero_n)]           # (the gardener's tiles: loaded with the character)
    for sheet, pal in (("tools", OBJ_TOOLS), ("items", OBJ_ITEMS), ("fx", OBJ_FX)):
        ims = Image.open(os.path.join(a.art, sheet + ".png"))
        for name, x, y, w, hh, n in lay[sheet]:
            enames.append("SPR_%s = %d" % (name.upper(), idx))
            for f in range(n):
                rows.append("{%d, %d, %d, %d}" % (len(tiles), w, hh, pal))
                tiles += split8(indices(ims, x + f * w, y, w, hh))
                idx += 1
    pop_tile = len(tiles)
    kit_tile = pop_tile + POP_TILES
    h.append("#define HERO_TILES %d\n#define POP_TILE %d\n#define POP_TILES %d\n#define KIT_OBJ_TILE %d" %
             (hero_n, pop_tile, POP_TILES, kit_tile))
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(enames), idx))
    h.append("typedef struct pp_sprite_def { uint16_t tile; uint8_t w, h, pal; } pp_sprite_def;")
    h.append("extern const pp_sprite_def pp_spr[SPR_COUNT];")
    h.append("extern const uint8_t pp_obj_tiles[];\nextern const int pp_obj_tile_count;")
    h.append("extern const uint8_t pp_hero_tiles[3][HERO_TILES * 32];")
    c.append("const pp_sprite_def pp_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("pp_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int pp_obj_tile_count = %d;" % len(tiles))
    c.append("const uint8_t pp_hero_tiles[3][HERO_TILES * 32] = {")
    for t in hero_tiles:
        c.append("{" + ", ".join("0x%02x" % b for b in rsasset.tiles_bytes(t)) + "},")
    c.append("};")
    assert kit_tile + 118 <= 1024, "the sprites' tiles overflow"
    stats.append("OBJ %d (+%d pops, kit at %d)" % (len(tiles), POP_TILES, kit_tile))

    # ---- the garden's tiles -------------------------------------------------------------------------------------------
    img = Image.open(os.path.join(a.art, "ground.png"))
    gt, gnames = [], []
    for name, x, y, w, hh, n in lay["ground"]:
        gnames.append("GT_%s = %d" % (name.upper(), len(gt)))
        gt += split8(indices(img, x, y, w, hh))
    h.append("enum { %s, GT_COUNT = %d };" % (", ".join(gnames), len(gt)))
    h.append("extern const uint8_t pp_ground_tiles[];")
    c.append(rsasset.c_bytes("pp_ground_tiles", rsasset.tiles_bytes(gt)))
    stats.append("ground %d" % len(gt))

    # ---- the palettes -----------------------------------------------------------------------------------------------------
    for key in ("soft", "ground", "ground_night", "tools", "items", "fx"):
        c.append(rsasset.c_u16("pp_pal_" + key, pal555([tuple(v) for v in pals[key]])))
        h.append("extern const uint16_t pp_pal_%s[16];" % key)
    c.append("const uint16_t pp_pal_hero[3][16] = {")
    for cname in ("hedgehog", "tortoise", "hen"):
        c.append("{" + ", ".join("0x%04x" % v for v in pal555([tuple(v) for v in pals[cname]])) + "},")
    c.append("};")
    h.append("extern const uint16_t pp_pal_hero[3][16];")

    # ---- the asset pack: the music --------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        d = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, d, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(d)))
    c.append("const rs_asset_entry pp_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry pp_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
