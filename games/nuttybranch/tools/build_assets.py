#!/usr/bin/env python3
"""Nutty Branch asset build: the code-drawn art (make_art.py: art/*.png, sprites.json, palettes.json) -> tiles,
maps, palettes and the sprite table; the music (make_music.py) -> build/gen/nuttybranch/assets.c + assets.h.

    build_assets.py --out build/gen/nuttybranch [--art games/nuttybranch/art] [--tileset IGNORED]

Colours are mapped to palette indices exactly (the art is drawn in the fixed palettes of make_art.py): a colour
outside its palette is an error.
MIT licence, (c) 2026 Pierre-Louis Boyer (8BCraft): games/nuttybranch/LICENSE.
"""
import argparse
import glob
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ROOT = os.path.abspath(os.path.join(GAME, "..", ".."))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "games", "common", "tools"))
import rsasset  # noqa: E402
import house_style as hs  # noqa: E402
import make_art  # noqa: E402

PAL_BARK, PAL_SCENE, PAL_LOGO = 1, 2, 5
OBJ_PAL = {"hero": 0, "wood": 2, "col": 6, "bird": 7}          # OBJ 1, 4, 5: players 2-4; OBJ 3: the house kit
VR_BG1, VR_BG2, VR_BG3, VR_OBJ = 0, 1024, 1536, 3072
KIT_OBJ_TILE = 900                                               # the kit's sprites (house_ui.h HU_OBJ_TILES) after ours


def c555(rgb):
    return rsasset.to555(tuple(rgb))


def index_image(path, pal):
    """A PNG drawn in `pal` (index -> RGB, 1..15) -> rows of indices (0 = transparent)."""
    img = rsasset.load(path)
    look = {}
    for i, c in enumerate(pal):
        if i and c is not None:
            k = c555(c)
            assert k not in look, "%s: palette entries %d and %d are the same colour in RGB555" % (path, look[k], i)
            look[k] = i
    W, H = img.size
    cells = rsasset.cell(img, 0, 0, W, H)
    out = []
    for y, row in enumerate(cells):
        r = []
        for x, v in enumerate(row):
            if v is None:
                r.append(0)
            else:
                assert v in look, "%s: colour %s at (%d, %d) is not in the palette" % (path, rsasset.rgb888(v), x, y)
                r.append(look[v])
        out.append(r)
    return out


def bg_tiles(idx, map_w, map_h, pal):
    """Indexed rows -> deduplicated tiles (flips too) and a map_w x map_h map on BG palette `pal`."""
    tiles, index, mp = [[0] * 64], {tuple([0] * 64): (0, 0, 0)}, []
    for ty in range(map_h):
        for tx in range(map_w):
            t = [idx[ty * 8 + y][tx * 8 + x] for y in range(8) for x in range(8)]
            key = tuple(t)
            hit = index.get(key)
            if hit is None:
                for hf, vf, f in ((1, 0, rsasset.hflip), (0, 1, rsasset.vflip), (1, 1, lambda q: rsasset.vflip(rsasset.hflip(q)))):
                    k2 = tuple(f(t))
                    if k2 in index:
                        b = index[k2]
                        hit = (b[0], hf ^ b[1], vf ^ b[2])
                        break
            if hit is None:
                tiles.append(t)
                hit = (len(tiles) - 1, 0, 0)
                index[key] = hit
            mp.append(rsasset.rs_map(hit[0], pal, 0, hit[1], hit[2]))
    return tiles, mp


def arr16(name, data, static=False):
    return rsasset.c_u16(name, [v & 0xFFFF for v in data], static)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--art", default=os.path.join(GAME, "art"))
    ap.add_argument("--tileset", default="", help="ignored (the tiles are code-drawn)")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    if not os.path.exists(os.path.join(a.art, "sprites.json")):
        make_art.write_all(a.art)
    pals = json.load(open(os.path.join(a.art, "palettes.json")))
    man = json.load(open(os.path.join(a.art, "sprites.json")))
    bands = pals["bands"]
    c = ["/* Generated by games/nuttybranch/tools/build_assets.py. Do not edit. */", '#include "assets.h"\n']
    h = ["/* Generated by games/nuttybranch/tools/build_assets.py. Do not edit. */",
         "#ifndef GM_ASSETS_H\n#define GM_ASSETS_H\n#include <stdint.h>\n#include \"rs.h\"\n",
         "#define VR_BG1 %d\n#define VR_BG2 %d\n#define VR_BG3 %d\n#define VR_OBJ %d\n#define KIT_OBJ_TILE %d" %
         (VR_BG1, VR_BG2, VR_BG3, VR_OBJ, KIT_OBJ_TILE),
         "#define PAL_BARK %d\n#define PAL_SCENE %d\n#define PAL_LOGO %d" % (PAL_BARK, PAL_SCENE, PAL_LOGO),
         "#define BANDS %d" % len(bands)]
    stats = []

    # ---- BG2 (affine): the branch texture, 512x256 = a 64x32 map ------------------------------------------------
    bark0 = [None] + [tuple(v) for v in bands[0]["bark"][1:]]
    idx = index_image(os.path.join(a.art, "branch.png"), bark0)
    tiles, mp = bg_tiles(idx, 64, 32, PAL_BARK)
    c.append(rsasset.c_bytes("gm_branch_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gm_branch_tile_count = %d;" % len(tiles))
    c.append(arr16("gm_branch_map", mp))
    h.append("extern const uint8_t gm_branch_tiles[];\nextern const int gm_branch_tile_count;\n"
             "extern const uint16_t gm_branch_map[64 * 32];")
    stats.append("branch %d" % len(tiles))
    assert VR_BG2 + len(tiles) <= VR_BG3, "the branch tiles overlap BG3's"

    # ---- BG3: the backdrop (256x256 = a 32x32 map) -------------------------------------------------------------------
    scene0 = [None] + [tuple(v) for v in bands[0]["scene"][1:]]
    idx = index_image(os.path.join(a.art, "backdrop.png"), scene0)
    tiles, mp = bg_tiles(idx, 32, 32, PAL_SCENE)
    c.append(rsasset.c_bytes("gm_scene_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gm_scene_tile_count = %d;" % len(tiles))
    c.append(arr16("gm_scene_map", mp))
    h.append("extern const uint8_t gm_scene_tiles[];\nextern const int gm_scene_tile_count;\n"
             "extern const uint16_t gm_scene_map[32 * 32];")
    stats.append("backdrop %d" % len(tiles))
    assert VR_BG3 + len(tiles) <= VR_OBJ, "the backdrop tiles overlap the sprites'"

    # ---- sprites --------------------------------------------------------------------------------------------------
    sheet = os.path.join(a.art, "sprites.png")
    group_pal = {g: [None] + [tuple(v) for v in p] for g, p in pals["groups"].items()}
    looks = {}
    for g, p in group_pal.items():
        lk = {}
        for i, col in enumerate(p):
            if i:
                k = c555(col)
                assert k not in lk, "group %s: entries %d and %d are the same in RGB555" % (g, lk[k], i)
                lk[k] = i
        looks[g] = lk
    img = rsasset.load(sheet)
    tiles, rows, names, counts = [], [], [], []
    for d in man:
        names.append("SPR_%s = %d" % (d["name"].upper(), len(rows)))
        counts.append("#define NFR_%s %d" % (d["name"].upper(), len(d["frames"])))
        lk = looks[d["group"]]
        for f in d["frames"]:
            cell = rsasset.cell(img, f["x"], f["y"], f["w"], f["h"])
            first = len(tiles)
            for t in rsasset.split_tiles(cell):
                ti = []
                for v in t:
                    if v is None:
                        ti.append(0)
                    else:
                        assert v in lk, "sprite %s: colour %s not in group %s" % (d["name"], rsasset.rgb888(v), d["group"])
                        ti.append(lk[v])
                tiles.append(ti)
            rows.append("{%d, %d, %d, %d, %d, %d, %d}" % (first, f["w"], f["h"], OBJ_PAL[d["group"]], f["ax"], f["ay"],
                                                          d["mirror"]))
    assert len(tiles) <= KIT_OBJ_TILE, "the sprites (%d tiles) overlap the kit's: raise KIT_OBJ_TILE" % len(tiles)
    h.append("enum { %s, SPR_COUNT = %d };" % (", ".join(names), len(rows)))
    h.append("\n".join(counts))
    h.append("typedef struct gm_sprite_def { uint16_t tile; uint8_t w, h, pal; int8_t ax, ay; uint8_t mirror; } gm_sprite_def;")
    h.append("extern const gm_sprite_def gm_spr[SPR_COUNT];")
    h.append("extern const uint8_t gm_obj_tiles[];\nextern const int gm_obj_tile_count;")
    c.append("const gm_sprite_def gm_spr[SPR_COUNT] = {\n    " + ",\n    ".join(rows) + "};")
    c.append(rsasset.c_bytes("gm_obj_tiles", rsasset.tiles_bytes(tiles)))
    c.append("const int gm_obj_tile_count = %d;" % len(tiles))
    stats.append("OBJ %d" % len(tiles))

    # ---- palettes: the four squirrels (house_style.player_palettes), the props, the bands ------------------------------
    hero = [tuple(v) for v in pals["groups"]["hero"]]
    lo, hi = pals["fur_hues"]
    sw = hs.player_palettes(hero, lo, hi, pals["p2_shift"])
    objp = [0] * 128
    for p, slot in enumerate((0, 1, 4, 5)):
        objp[slot * 16:slot * 16 + 16] = rsasset.palette16([rsasset.to555(v) for v in sw[p]])
    for g in ("wood", "col", "bird"):
        s = OBJ_PAL[g]
        objp[s * 16:s * 16 + 16] = rsasset.palette16([rsasset.to555(tuple(v)) for v in pals["groups"][g]])
    c.append(arr16("gm_obj_pals", objp))
    h.append("extern const uint16_t gm_obj_pals[128];")
    for key in ("bark", "scene", "wood", "col"):
        vals = []
        for b in bands:
            vals += [0] + [rsasset.to555(tuple(v)) for v in b[key][1:16]]
        c.append(arr16("gm_band_%s" % key, vals))
        h.append("extern const uint16_t gm_band_%s[BANDS * 16];" % key)
    sky = []
    for b in bands:
        for col in b["sky"]:
            sky += [col[0], col[1], col[2]]
    c.append("const uint8_t gm_band_sky[BANDS * 12] = {%s};" % ", ".join(str(v) for v in sky))
    h.append("extern const uint8_t gm_band_sky[BANDS * 12];")

    # ---- the asset pack: the music ------------------------------------------------------------------------------------
    music_dir = os.path.join(a.out, "music")
    subprocess.check_call([sys.executable, os.path.join(HERE, "make_music.py"), music_dir])
    pack = [("music/" + os.path.basename(p), p) for p in sorted(glob.glob(os.path.join(music_dir, "*.mod")))]
    entries = []
    for i, (name, path) in enumerate(pack):
        data = open(path, "rb").read()
        c.append(rsasset.c_bytes("pack_%d" % i, data, static=True))
        entries.append('    {"%s", pack_%d, %d}' % (name, i, len(data)))
    c.append("const rs_asset_entry gm_assets[] = {\n" + ",\n".join(entries) + ",\n    {0, 0, 0}};")
    h.append("extern const rs_asset_entry gm_assets[];\n#endif")

    open(os.path.join(a.out, "assets.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(a.out, "assets.h"), "w").write("\n".join(h) + "\n")
    print("assets: tiles %s, %d pack files -> %s" % (", ".join(stats), len(pack), a.out))


if __name__ == "__main__":
    main()
